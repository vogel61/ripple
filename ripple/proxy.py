# launchd is pid 1, and a job's process is its direct child. That is the fact an
# inherited environment cannot fake: the gateway's child has the gateway as its
# parent, whatever `XPC_SERVICE_NAME` says.
LAUNCHD_PID = 1

# How long the read-only ownership query may take before the answer is "no".
LAUNCHCTL_TIMEOUT_SECONDS = 5.0

# `launchctl print` for a label that is not in the domain: "Could not find
# service … in domain for user gui: 501", measured. Any other non-zero exit is
# not an answer (#29).
NO_SUCH_SERVICE = 113


def _supervisor_marker() -> str | None:
    """The launchd job label in this process's environment, else None.

    launchd puts `XPC_SERVICE_NAME` into the environment of every job it starts —
    `launchctl print gui/$(id -u)/ai.ripple` shows `XPC_SERVICE_NAME => ai.ripple`
    for the running service, and `ps eww` on its pid shows the same.

    **`"0"` is not a label.** macOS's libxpc writes `XPC_SERVICE_NAME=0` into
    every process that is *not* a launchd job (a shell, a child of one, this
    pytest run) — measured here, not assumed: a prefix assignment
    `XPC_SERVICE_NAME=ai.ripple python …` comes out as `0` again, so the value
    cannot be faked from outside either. A real job label is never `0`, so the
    check is "present and not `0`".

    **A label is not a supervisor on its own (#27).** A process started by
    another launchd job inherits *that* job's label, which is why this function
    only reads the environment: whether the label means anything is decided by
    `supervision_state`, from the parent pid and the job's ownership.

    The label is only ever reported and passed to a read-only query, never
    executed or interpolated into a shell.
    """
    label = (os.environ.get("XPC_SERVICE_NAME") or "").strip()
    if not label or label == "0":
        return None
    return label


def _parent_pid() -> int:
    """The pid of this process's parent. launchd is pid 1 (#27)."""
    return os.getppid()


def _job_pid(printed: str) -> int | None:
    """The `pid` of the job in `launchctl print`'s output, or None if it has none.

    Measured on this machine (15.11.2026), the fields of the job dictionary are
    indented with exactly one tab and a job that is not running has no `pid`
    line at all:

        gui/501/ai.ripple = {
        \tactive count = 1
        \t…
        \tpid = 11129
        \tstate = running

    Nested dictionaries (`endpoints`, `event triggers`) are indented deeper, so
    the single-tab anchor keeps a nested `pid` from being read as the job's. If
    the format ever changes the parse finds nothing and the guard refuses — the
    direction in which no service can be lost.
    """
    match = re.search(r"^[ \t]pid = (\d+)$", printed, re.MULTILINE)
    return int(match.group(1)) if match else None


def _query_launchd_owns_pid(label: str) -> bool | None:
    """Does the job `label` in this user's GUI domain name *this* pid?

    Read-only by construction: `print` is launchd's query verb, the argv is a
    list (no shell, so there is no string to interpolate), and the output is
    parsed, never executed. The label comes from the environment, so it is also
    required to be a single path component before it is handed to the tool — a
    label is a name, not an address.

    **Three answers, not two (#29).** `True` is ownership. `False` is an answer:
    launchd said no — rc 113 (`Could not find service "…" in domain for user
    gui: 501`, measured) or a job block naming another pid. `None` is no answer
    at all: no `launchctl` on this machine, a timeout, a label that is not a
    name. The distinction matters to the operator — "this job does not own you"
    and "nobody could tell" are different problems — so it is carried as
    `reason_code` instead of being flattened into one sentence.

    Nothing that is not `True` enables the control: guessing True would end a
    process nobody restarts, which is the failure this guard exists to prevent.
    """
    if not label or "/" in label or "\n" in label:
        return None
    tool = shutil.which("launchctl")
    if tool is None:
        return None
    try:
        proc = subprocess.run(
            [tool, "print", f"gui/{os.getuid()}/{label}"],
            capture_output=True, text=True, timeout=LAUNCHCTL_TIMEOUT_SECONDS,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    if proc.returncode != 0:
        # rc 113 is launchd's own "no such service in this domain" — an answer.
        return False if proc.returncode == NO_SUCH_SERVICE else None
    return _job_pid(proc.stdout) == os.getpid()


# (pid, label) → ownership already proven. See `_launchd_owns_pid`.
_owns_pid_memo: dict[tuple[int, str], bool] = {}


def _launchd_owns_pid(label: str) -> bool | None:
    """`_query_launchd_owns_pid`, memoised for the one answer that cannot change.

    A *proven* ownership is kept for the life of the process: launchd removes a
    job by terminating its processes, so a process that is still here after
    proving "job X owns me" cannot become an orphan while it runs. A negative
    answer is never kept — a transient failure must not leave the control
    disabled. `/healthz` carries this state and the page polls it every 2 s, so
    without the memo every poll would spawn a process.
    """
    key = (os.getpid(), label)
    if _owns_pid_memo.get(key):
        return True
    owned = _query_launchd_owns_pid(label)
    if owned:
        _owns_pid_memo[key] = True
    return owned


def supervision_state(*, ppid: int | None = None,
                      owns: Callable[[str], bool | None] | None = None) -> dict[str, Any]:
    """Would something start this process again if it ended? (#22, #27, #29)

    Three facts, asked in this order; the first one that fails is the reason the
    operator reads in the dialog, and `cause` is the same answer for the log:

    1. **A label** (`no_label`) — launchd writes `XPC_SERVICE_NAME` into the
       environment of the job it starts; unset or `0` is not a launchd job.
    2. **launchd as the parent** (`inherited`) — a child of another job carries
       that job's label, so the label alone is exactly the false positive this
       issue is about. A real job's process has ppid 1.
    3. **Ownership** (`unowned`) — two jobs can carry the same string in an
       environment, so `launchctl print` has to name this pid.

    `cause` is the word for the log and stays three-valued; `reason_code` is the
    page's closed set (#29) and splits the third fact in two: `label_not_owner`
    when launchd answered "not this pid", `query_failed` when it did not answer
    at all. `reason_params` carries the values the catalog sentence interpolates
    — the page never parses numbers out of prose.

    `ppid` and `owns` are a **test seam, not a switch**: the pytest process is
    never launchd's child, so a test has to state the two OS facts it cannot
    produce. The defaults read the live process, and nothing here consults the
    config or an environment variable — no flag turns the guard off.
    """
    label = _supervisor_marker()
    if label is None:
        return {"supervised": False, "supervisor": None, "cause": "no_label",
                "reason": UNSUPERVISED_REASON, "reason_code": "no_label",
                "reason_params": None}
    parent = _parent_pid() if ppid is None else ppid
    if parent != LAUNCHD_PID:
        return {"supervised": False, "supervisor": None, "cause": "inherited",
                "reason": INHERITED_LABEL_REASON.format(label=label, ppid=parent),
                "reason_code": "inherited_label",
                "reason_params": {"label": label, "ppid": parent}}
    checker = _launchd_owns_pid if owns is None else owns
    owned = checker(label)
    if owned is None:
        return {"supervised": False, "supervisor": None, "cause": "unowned",
                "reason": QUERY_FAILED_REASON.format(label=label),
                "reason_code": "query_failed",
                "reason_params": {"label": label}}
    if not owned:
        return {"supervised": False, "supervisor": None, "cause": "unowned",
                "reason": UNOWNED_LABEL_REASON.format(label=label, pid=os.getpid(),
                                                      uid=os.getuid()),
                "reason_code": "label_not_owner",
                "reason_params": {"label": label, "pid": os.getpid()}}
    return {"supervised": True, "supervisor": label, "cause": None, "reason": None,
            "reason_code": None, "reason_params": None}


def _hard_exit(code: int) -> None:
    """End the process the way a supervised restart has to: immediately.

    `os._exit` on purpose. A graceful shutdown would first drain the streams the
    confirmation dialog just warned about, and launchd decides on the exit status
    alone. Logging is flushed by hand because `os._exit` skips `atexit`.
    """
    logging.shutdown()
    os._exit(code)


def _json_usage(payload: bytes) -> dict[str, Any] | None:
    """The `usage` object of a non-streamed response body."""
    try:
        data = json.loads(payload.decode("utf-8", "replace"))
    except (ValueError, UnicodeDecodeError):
        return None
    if not isinstance(data, dict):
        return None
    usage = data.get("usage")
    return usage if isinstance(usage, dict) else None


def _needs_cold_load(decision) -> bool:
    """Does the chosen host have to load the model before it can answer?

    Read from the placement tier, not from `Decision.reason`: `degraded_host`
    overrides the reason, and a degraded host that has to load must still get its
    probes suspended — that combination is exactly the 14.11. incident.

    **`evict_idle` loads too.** A request that evicts an idle model first still
    ends with a cold load of the model it asked for, and it is the *normal* path
    on a node that holds a big resident model — the first production cold load
    after deployment was an `evict_idle` and went unsupervised for the length of
    one probe interval. Any tier that leaves the model non-resident counts.
    """
    for cand in decision.candidates:
        if cand.host is decision.host:
            return cand.tier in (TIER_COLD_LOAD, TIER_EVICT_IDLE)
    return False


def _evicts_idle(decision) -> bool:
    """Is this load one that had to unload an idle model first?

    The subset of `_needs_cold_load`, and read from the tier for the same
    reason: a degraded host carries the reason `degraded_host` while its tier
    stays `evict_idle`, so counting from `Decision.reason` would silently lose
    exactly those loads.
    """
    for cand in decision.candidates:
        if cand.host is decision.host:
            return cand.tier is TIER_EVICT_IDLE
    return False


def _sse_json(event: bytes) -> dict | None:
    """The JSON object of one SSE event, or None for `[DONE]`/non-JSON events."""
    for line in event.split(b"\n"):
        if not line.startswith(b"data:"):
            continue
        raw = line[5:].strip()
        if not raw or raw == b"[DONE]":
            continue
        try:
            obj = json.loads(raw)
        except ValueError:
            continue
        if isinstance(obj, dict):
            return obj
    return None

