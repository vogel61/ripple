        @app.post("/admin/discover")
        async def nodes_discover(request: Request) -> JSONResponse:
            """Sweep a CIDR for oMLX nodes — `ripple discover --scan`, from the page.

            The same sweep the CLI runs (`ripple/discover.py`), behind the admin
            key because a sweep is traffic on someone's network and the answer
            lists machines. It writes nothing: the candidates are read, and
            adding one is a second, explicit `POST /admin/nodes` (issue #71).

            `port` and `timeout` are per address; the sweep is bounded by
            `MAX_SCAN_ADDRESSES` (a /16), so a wider CIDR is a 400 instead of a
            minute of silence.
            """
            denied = self._require_admin(request)
            if denied is not None:
                return denied
            body = await _json_body(request)
            cidr = str(body.get("cidr") or request.query_params.get("cidr") or "").strip()
            if not cidr:
                return JSONResponse({"error": {
                    "code": "cidr_required", "step": "cidr",
                    "message": "cidr required — e.g. {\"cidr\": \"192.0.2.0/24\"}"}},
                    status_code=400)
            try:
                port = int(body.get("port") or request.query_params.get("port") or 8000)
                timeout = float(body.get("timeout") or request.query_params.get("timeout") or 0.5)
            except (TypeError, ValueError):
                return JSONResponse({"error": {
                    "code": "invalid_scan", "step": "cidr",
                    "message": "port must be an integer and timeout a number"}},
                    status_code=400)
            started = time.monotonic()
            try:
                found = await scan_network(cidr, port=port, timeout=timeout)
            except ValueError as exc:
                # A CIDR the sweep refuses (too large, or not a network at all).
                # The step is `cidr` so the page can name the field, not the
                # parser.
                return JSONResponse({"error": {"code": "bad_cidr", "step": "cidr",
                                               "message": str(exc)}}, status_code=400)
            took = time.monotonic() - started
            candidates = [self._candidate_row(f) for f in found]
            log.warning("node_discover cidr=%s port=%d found=%d took=%.2fs by=%s",
                        cidr, port, len(candidates), took,
                        self.client_address(request) or "-")
            return JSONResponse({"cidr": cidr, "port": port, "timeout": timeout,
                                 "found": candidates, "count": len(candidates),
                                 "took_seconds": round(took, 3)})

        @app.delete("/admin/nodes/{name}")
        async def nodes_delete(name: str, request: Request,
                               timeout: Optional[float] = None) -> JSONResponse:
            """Remove a node with a drain: no new work, wait for zero, then out.

            A node that `config.yaml` declares is refused — the file is the
            baseline and a page click must not be able to delete a machine from
            it. Disabling it is the way to take it out for good
            (`POST /admin/nodes/{name}/disable`).

            The wait is bounded by `fleet.drain_seconds` (or `?timeout=`). On
            expiry nothing is removed: the answer names the requests still in
            flight and the node is left **disabled** — out of the pool, still in
            the fleet, still in the overlay — rather than half-removed.
            """
            denied = self._require_admin(request)
            if denied is not None:
                return denied
            host = self.fleet.get(name)
            if host is None:
                return JSONResponse({"error": {"message": f"unknown node {name}"}},
                                    status_code=404)
            if host.cfg.source == "config":
                return JSONResponse({"error": {
                    "code": "config_host",
                    "message": (f"{name} is declared in config.yaml and cannot be "
                                f"deleted at runtime — the file is the baseline. "
                                f"Disable it instead: POST /admin/nodes/{name}/disable "
                                f"(it stays in the file, out of the pool, and the "
                                f"decision survives a restart)")}}, status_code=409)
            outcome = await self.fleet.drain(name, timeout=timeout)
            if not outcome["drained"]:
                self._persist_disabled(host)
                log.warning("node_remove_refused name=%s inflight=%d waited=%.2fs",
                            name, outcome["inflight"], outcome["waited_seconds"])
                return JSONResponse({"error": self._drain_answer(host, outcome)},
                                    status_code=409)
            released = self._release_threads(name)
            self.fleet.remove(name)
            self.overlay.drop(name)
            save_overlay(self.overlay)
            self.host_stats.forget_host(name)
            log.warning("node_removed name=%s waited=%.2fs threads_released=%d by=%s",
                        name, outcome["waited_seconds"], released,
                        self.client_address(request) or "-")
            return JSONResponse({"removed": True, "node": name, "source": "overlay",
                                 "waited_seconds": outcome["waited_seconds"],
                                 "threads_released": released,
                                 "inflight": 0})

        @app.post("/admin/nodes/{name}/disable")
        async def nodes_disable(name: str, request: Request,
                                timeout: Optional[float] = None) -> JSONResponse:
            """Take a node out for good, keeping its entry (the open decision).

            Disabling drains like a removal — new work stops at once, running
            requests finish — but the host stays in the fleet and in the overlay,
            so `POST /admin/nodes/{name}/enable` brings it back with one call and
            a restart does not bring it back on its own.
            """
            denied = self._require_admin(request)
            if denied is not None:
                return denied
            host = self.fleet.get(name)
            if host is None:
                return JSONResponse({"error": {"message": f"unknown node {name}"}},
                                    status_code=404)
            outcome = await self.fleet.drain(name, timeout=timeout)
            self._persist_disabled(host)
            if outcome["drained"]:
                # Nothing is running any more: the node is disabled, not still
                # draining. The distinction matters on the page — a countdown
                # that never ends would look like a removal that hung.
                host.end_drain()
            log.warning("node_disabled name=%s source=%s inflight=%d drained=%s by=%s",
                        name, host.cfg.source, outcome["inflight"], outcome["drained"],
                        self.client_address(request) or "-")
            return JSONResponse({
                "node": self._node_row(host),
                "disabled": True,
                # The node is out of the pool either way; what is *not* finished
                # is the running work, and that is said rather than rounded away.
                "drained": outcome["drained"],
                "inflight": outcome["inflight"],
                "models": outcome["models"],
                "waited_seconds": outcome["waited_seconds"],
            })

        @app.post("/admin/nodes/{name}/enable")
        async def nodes_enable(name: str, request: Request) -> JSONResponse:
            """Put a disabled node back into the pool.

            The counterpart of `disable`, and it works across a restart: a node
            that the overlay disabled is not built into the fleet at start-up, so
            enabling it re-resolves it and inserts it the same way an add does.
            """
            denied = self._require_admin(request)
            if denied is not None:
                return denied
            host = self.fleet.get(name)
            host_cfg = self.cfg.host(name)
            if host is None and host_cfg is None:
                return JSONResponse({"error": {"message": f"unknown node {name}"}},
                                    status_code=404)
            if host_cfg is not None:
                host_cfg.enabled = True
                self.overlay.clear_override(name, "enabled")
            block = self.overlay.hosts.get(name)
            if block is not None:
                block["enabled"] = True
            if host is None:
                assert host_cfg is not None
                try:
                    host = await self.fleet.add(host_cfg)
                except HostUnresolved as exc:
                    return JSONResponse({"error": {
                        "code": "unresolved",
                        "message": f"{name} could not be resolved: {exc}",
                        "last_error": exc.host.last_error}}, status_code=502)
            else:
                host.cfg.enabled = True
                host.end_drain()
            save_overlay(self.overlay)
            self.host_stats.add_host(name)
            self._apply_windows()
            log.warning("node_enabled name=%s source=%s address=%s by=%s",
                        name, host.cfg.source, host.resolved_address,
                        self.client_address(request) or "-")
            return JSONResponse({"node": self._node_row(host), "enabled": True})

