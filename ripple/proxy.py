# -- the arriving turn (issue #95, §6.4) ------------------------------------
# `stats.UsageLedger` stores `prompt_tokens_per_second` per (thread, host) row,
# and that number is only a *prefill rate* on a cold prompt: measured on the
# live server, 1254 tok/s cold against 14.46 tok/s on a 700/702-token cache hit,
# because the server prices the uncached remainder only. A rolling mean that
# mixes the two understates a node by two orders of magnitude and makes every
# move look free, so a row counts as a measurement of the node's prefill rate
# only when its `cached_tokens` is ~0 (`COLD_PP_CACHE_RATIO` of the prompt — a
# real hit is ~98 %, the tolerance is for a block boundary) and the prompt was
# long enough for the rate not to be dominated by fixed overhead
# (`COLD_PP_MIN_TOKENS`). Everything else falls back to the configured
# `placement.rebind.default_pp_tps`.
COLD_PP_CACHE_RATIO = 0.02
COLD_PP_MIN_TOKENS = 256

