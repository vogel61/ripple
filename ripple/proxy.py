def _migration_note(decision: MigrationDecision) -> str:
    """The `decision=` field's sentence for one arriving-turn decision.

    §6.4 asks that a move and a refusal both carry the numbers that decided
    them, so the line shows the arithmetic (`cost`, `gain` per turn, `turns_left`,
    `benefit` against `threshold`) and the fleet verdict (`Δtotal`) beside the
    reason. A refusal carries whatever of those it got to compute — that is the
    point of naming `no_repayment` instead of `thread`.
    """
    priced = decision.priced or {}

    def number(key: str) -> float | None:
        value = priced.get(key)
        return float(value) if isinstance(value, (int, float)) else None

    parts = [f"migrate {decision.reason}"]
    if priced.get("dst"):
        parts.append(f"dst={priced['dst']}")
    for key, label, unit in (("cost_s", "cost", "s"),
                             ("gain_per_turn_s", "gain", "s/turn"),
                             ("benefit_s", "benefit", "s"),
                             ("threshold_s", "threshold", "s")):
        value = number(key)
        if value is not None:
            parts.append(f"{label}={value:g}{unit}")
    turns_left = number("turns_left")
    if turns_left is not None:
        parts.append(f"turns_left={turns_left:g}")
    delta_total = number("delta_total")
    if delta_total is not None:
        parts.append(f"delta_total={delta_total:+.1f}")
    band = number("band_s")
    if band is not None:
        parts.append(f"band={band:g}s/{priced.get('band')}")
    if decision.detail:
        parts.append(f"({decision.detail})")
    return " ".join(parts)


# -- restart (issue #22) -----------------------------------------------------
# The restart is the *exit*: launchd's KeepAlive starts the job again. No command
# string anywhere and no shell — there is nothing an operator could inject,
# because nothing is executed. The single process the guard starts is the
# read-only `launchctl print` query in `_query_launchd_owns_pid` (#27), which
# only proves that the exit will be noticed.
#
# The delay is what makes the 202 possible: the response has to leave the socket
# before the process that is answering stops existing. One second is short enough
# that nobody waits, long enough for a loopback round trip plus the dashboard's
# fetch to resolve.
RESTART_DELAY_SECONDS = 1.0

# Any non-zero status. `deploy/ai.ripple.plist` carries
# `KeepAlive → SuccessfulExit → false`, i.e. launchd restarts the job when it
# exits *unsuccessfully*; a zero exit would be read as "done on purpose" and the
# service would stay down. `tests/test_restart.py` pins the two together.
RESTART_EXIT_CODE = 75

