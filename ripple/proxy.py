async def _json_body(request: Request) -> dict[str, Any]:
    """The JSON body of an admin request, or `{}`.

    The admin routes take query parameters (the maintenance shape). The model
    policy routes accept the same keys in a JSON body as well, because a
    dashboard toggle posts one; an absent or unparsable body is simply empty.
    """
    try:
        body = await request.json()
    except (ValueError, json.JSONDecodeError):
        return {}
    return body if isinstance(body, dict) else {}


def _flag(value: Any) -> bool:
    """A boolean from a query string or a JSON body (`?dry_run=true`).

    `True` in a body is a bool and `"true"` in a query is a string, and both
    mean the same thing to the caller. Only an explicit yes counts: an absent
    parameter is a write, which is the safe default for the one route where
    getting this wrong would change the fleet.
    """
    if isinstance(value, bool):
        return value
    return str(value or "").strip().lower() in {"1", "true", "yes", "on"}


def _bearer(request: Request) -> str | None:
    """The token a client presented, if any. Never logged, never stored."""
    raw = request.headers.get("authorization") or ""
    if raw.lower().startswith("bearer "):
        token = raw[7:].strip()
        if token:
            return token
    return request.headers.get("x-api-key") or None


def _is_loopback(request: Request) -> bool:
    client = request.client
    host = (client.host if client else "") or ""
    return host in {"127.0.0.1", "::1", "localhost"}


def _ip(text: str) -> str | None:
    """The canonical form of an IP literal, or None.

    `X-Forwarded-For` is free text: an entry may be a hostname, a `host:port`
    pair or garbage. Only something that really is an address may become an
    origin, so anything else is dropped rather than written into the log.
    """
    try:
        return str(ipaddress.ip_address(text.strip()))
    except ValueError:
        return None


def _thread_source(thread: Any, source: str | None = None) -> str | None:
    """Where a thread id comes from: `sid`, `fp` or `sid+fp`.

    Read from the key itself, not from the registry's `source`: a thread adopted
    by prefix match keeps the identity it was opened with, and that identity is
    exactly what the key prefix says (`sid:…` from `affinity.header`, otherwise
    a prompt fingerprint). No thread, no source.

    `source` is how *this* request found the thread (`_identify`). A prefix match
    into a thread a header opened never consulted the header, so calling it
    `sid` names a source this request did not use — and makes it impossible to
    count header traffic without guessing (issue #68). `sid+fp` says both
    halves: a sid thread, reached by prompt similarity.
    """
    if thread is None:
        return None
    if not thread.key.startswith("sid:"):
        return "fp"
    return "sid+fp" if source == "prefix_match" else "sid"


def _client_key(request: Request) -> str | None:
    """FA-15: the configured upstream key wins; otherwise the client key is
    passed through. Keys never appear in logs or /stats."""
    auth = request.headers.get("authorization") or ""
    if auth.lower().startswith("bearer "):
        return auth[7:].strip() or None
    return None


class Ripple:
    def __init__(self, cfg: Config) -> None:
        self.cfg = cfg
        self.stats = Stats()
        self.registry = ThreadRegistry(cfg.affinity)
        # Requests per (host, model) inside the served window (issue #91). The
        # distribution block counts thread *slots*, so a model that is loaded and
        # serving traffic without a warm thread had no row there at all — it
        # looked absent while it was working. `by_model` in `/stats` counts since
        # the start and knows no host and no window; this deque is the additive
        # answer: one entry per dispatch, pruned by the window on read, so
        # nothing existing changes shape. Bounded because `/healthz` is polled
        # every 2 s and the number only has to cover the window, not the uptime.
        self._request_times: deque[tuple[float, str, str]] = deque(maxlen=20000)
        # The operator's model policy (issue #11) — a (host, model) pair that is
        # `disabled` or `hidden`. Loaded before the fleet is built, so the very
        # first request after a restart already respects it: a model switched
        # off for a reason must not be served for the seconds until someone
        # clicks.
        self.policy: ModelPolicy = load_policy(cfg.placement.model_policy_file)
        # The runtime overlay (issue #70), merged **before** the fleet is built:
        # a node the operator added at the page is a fleet member from the first
        # probe tick on, and a node he disabled is out of the pool from the first
        # request on — not from the first click after the restart. `config.yaml`
        # is only read here, never written.
        self.overlay = load_overlay(cfg.fleet.file, persist=cfg.fleet.persist)
        cfg.warnings.extend(apply_overlay(cfg, self.overlay))
        self.fleet = Fleet(cfg, self.stats, policy=self.policy)
        # The per-host ledger (issue #33): what each node did since the start,
        # persisted and resettable. Read before the app is built, so the very
        # first `/healthz` after a restart shows the numbers of the last run and
        # not zeros. A missing or unreadable file means zeros and one warning.
        self.host_stats = HostStats([h.cfg.name for h in self.fleet.hosts],
                                    path=cfg.stats.file,
                                    persist=cfg.stats.persist,
                                    flush_seconds=cfg.stats.flush_seconds)
        self.host_stats.load()
        # What the server measured itself, per (thread, host) (issue #98). In
        # memory and nowhere else: it is a property of the running process —
        # which thread is warm on which node — and a restart ends every thread
        # anyway, so a persisted copy would be a claim about a cache that is
        # gone. See `stats.UsageLedger`.
        self.usage = UsageLedger()
        # The sampler task (one activity call per host per probe tick) and the
        # cross-check clock. `_activity_warned` keeps a missing oMLX admin key
        # from writing a warning every ten seconds.
        self._host_stats_task: asyncio.Task | None = None
        self._cross_at: float = 0.0
        self._activity_warned = False
        self._lock = asyncio.Lock()
        self.proxy_client = httpx.AsyncClient(
            timeout=httpx.Timeout(connect=cfg.proxy.connect_timeout_seconds,
                                  read=None,            # FA-9: no read timeout
                                  write=cfg.proxy.connect_timeout_seconds,
                                  pool=cfg.proxy.connect_timeout_seconds),
            limits=httpx.Limits(max_connections=256, max_keepalive_connections=64),
            follow_redirects=False,
        )
        self._purge_task: asyncio.Task | None = None
        # The start-up update check (issue #123): the answer `/healthz` carries
        # and the one background task that produces it. `unknown` until the
        # answer arrives — the header draws nothing for it, so a slow network
        # costs the page no line and no wait. `disabled` is known before the
        # task would run, so it is set here rather than by the task.
        self.update_state: update_check.UpdateState = (
            update_check.UpdateState(state="disabled") if not cfg.update.check
            else update_check.UpdateState())
        self._update_task: asyncio.Task | None = None
        # The periodic placement optimizer (issue #80): its task and its own
        # move budget. A separate deque from `registry._rebinds` on purpose — the
        # optimizer's budget (`placement.optimizer.max_moves_per_hour`) and the
        # rebind guard's (`placement.rebind.max_per_hour`) are two numbers, and
        # one must not silently spend the other's.
        self._optimizer_task: asyncio.Task | None = None
        self._optimizer_moves: deque[float] = deque()
        # The sweep's recent `Δtotal` verdicts, one per scan, oldest first
        # (issue #95, §6.4). The arriving-turn decision's deadband is the
        # *observed* spread of exactly this number, so the samples have to come
        # from the scans that already happen — a constant band would be right
        # for no model pair. Kept longer than `band_samples` so a changed
        # setting takes effect on the next scans instead of a restart; the
        # decision slices the tail it needs. Empty until the optimizer has run,
        # which the decision reports as `band=unavailable` and falls back to
        # `rebind.min_gain_seconds`.
        self._delta_history: deque[float] = deque(maxlen=32)
        # Peers whose `X-Forwarded-For` may be believed, parsed once at startup
        # (config validation already refused anything that is not an address).
        self.trusted_proxies: tuple[ipaddress.IPv4Network | ipaddress.IPv6Network, ...] = tuple(
            ipaddress.ip_network(entry, strict=False)
            for entry in cfg.proxy.trusted_proxies)
        # Client keys (FA-23). Construction loads the file; a corrupt file fails
        # here, loudly, instead of on the first request.
        self.keys = KeyStore(cfg.auth.keys_file, admin_key=cfg.auth.admin_key)
        # Failed admin-key attempts per client address (issue #6). The admin key
        # is four digits; without this, anything on the LAN gets 10 000 guesses
        # a minute against `/admin/*`, which is the whole key space in an hour.
        self.admin_limits = AdminRateLimiter()
        # Operator-declared maintenance windows. Loaded before the app is built so
        # a node taken out for an update is out from the first request on, not
        # from the first dashboard click after the restart.
        self.maintenance: Maintenance = load_maintenance(
            cfg.placement.maintenance_file)
        self._apply_windows()
        # Lock refusals since start-up (issue #21). Counted here rather than in
        # `Stats`: `/stats` is assembled in `stats_payload()`, which is the one
        # place that shapes the payload, and this counter is incremented on the
        # request path right next to the refusal it belongs to.
        self.model_locked_refusals = 0
        # The restart control (issue #22). `_restart_task` is the pending exit —
        # it is the guard against a second click, not a flag that a caller could
        # set: the task exists exactly while a restart is on its way.
        self.restart_delay = RESTART_DELAY_SECONDS
        self._restart_task: asyncio.Task | None = None
        # Replication (issue #13): the transport is the one seam the tests
        # replace — everything else in `ripple.replication` is pure logic.
        self.replication_factory = (
            lambda c: replication.build_transport(c, client=self.proxy_client))
        self.app = self._build_app()

    # -- maintenance -------------------------------------------------------
    def _apply_windows(self) -> None:
        """Push the stored windows onto the hosts (startup and after a change).

        `HostRuntime.maintenance` is the only thing placement reads; the store is
        the source of truth for what the operator declared.
        """
        for host in self.fleet.hosts:
            win = self.maintenance.active(host.cfg.name)
            was = host.maintenance is not None
            host.maintenance = win.to_dict() if win else None
            if was and host.maintenance is None:
                # The window ended: the machine is the operator's to use again,
                # and a locked model has to be resident on it without a request
                # having to arrive first (issue #119). The node was healthy
                # throughout the window, so no probe transition would ever fire
                # here — this is the second trigger, not a second poller.
                self.fleet.request_preload(host)

    def _maintenance_view(self, host: HostRuntime) -> dict[str, Any]:
        """One node as the admin maintenance routes describe it.

        `state` is not derived here: it is `HostRuntime.reporting_state()`, the
        same call `/healthz` goes through (issue #90). Two endpoints answering
        about one node in one moment must not be able to disagree — the measured
        case was a disable that had started its drain, `/healthz` saying
        `draining` and this answer saying `healthy`.

        `draining` therefore means what it means in `/healthz`: a drain that
        `begin_drain` started, whatever the reason. The operator's other nuance —
        out of the pool while work is still running — is a different fact with a
        different name (`work_in_progress`), so one field name has one meaning on
        both paths.
        """
        threads = sum(1 for t in self.registry.threads.values() if t.host == host.cfg.name)
        return {
            "node": host.cfg.name,
            "maintenance": host.maintenance,
            "status": host.status,
            "state": host.reporting_state(),
            "in_pool": host.in_pool,
            "inflight": host.inflight,
            "threads": threads,
            "draining": host.draining,
            # Out of the pool and still working: the machine is not free to
            # touch yet, whatever took it out (window, drain, disable).
            "work_in_progress": not host.in_pool and host.inflight > 0,
        }

    # -- runtime fleet (issue #70) ------------------------------------------
    def _node_row(self, host: HostRuntime,
                  targets: dict[str, float] | None = None) -> dict[str, Any]:
        """One host as `/healthz → hosts[]` carries it (shared by the API answers).

        `POST /admin/nodes` must answer with the same row the page will poll a
        second later — otherwise the operator sees two different descriptions of
        the node he just added.
        """
        if targets is None:
            targets = self._thread_targets()
        row = host.to_dict(target_threads=targets.get(host.cfg.name, 0.0),
                           slots=self.registry.slots_on_host(host.cfg.name),
                           target_share=self.cfg.target_share(host.cfg))
        self._annotate_site(row, host.cfg)
        return row

    def _release_threads(self, name: str) -> int:
        """Give back the thread slots bound to a node that is leaving.

        A bound thread *is* a slot on its host (`ThreadRegistry.slots_on_host`),
        so a removed node would keep `max_threads` slots reserved for a machine
        that no longer exists — the count the dashboard divides by would be
        wrong for ever. The registry owns the accounting, so it does the
        forgetting; a thread with a request still running stays (the drain
        already waited for it).
        """
        released = self.registry.forget_host(name)
        if released:
            log.warning("threads_released node=%s count=%d", name, released)
        return released

    def _persist_disabled(self, host: HostRuntime) -> None:
        """Write the operator's "this node stays out" into the overlay.

        The one place the two sources differ: a node from `config.yaml` gets an
        `overrides` entry (it may be disabled, never deleted), a node the
        operator added gets `enabled: false` in its own block. Either way the
        decision survives the restart, which is the whole point of a disable.
        """
        host.cfg.enabled = False
        if host.cfg.source == "overlay":
            block = self.overlay.hosts.get(host.cfg.name)
            if block is not None:
                block["enabled"] = False
        else:
            self.overlay.override(host.cfg.name, enabled=False)
        save_overlay(self.overlay)

