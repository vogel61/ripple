        # -- the routing policy at the page (issue #78) ----------------------
        # One field per call, on a dotted path that is also the row's name in
        # block 6.5 and the key in the overlay file. `config.yaml` stays the
        # baseline: what changes here is written to `fleet.file` (now
        # `runtime.yaml`) and merged over the config at start-up, so it survives
        # a restart and the file the operator wrote stays byte-identical.
        def _policy_error(status: int, error: str, path: str,
                          message: str) -> JSONResponse:
            return JSONResponse({"error": error, "path": path, "message": message},
                                status_code=status)

        @app.patch("/admin/config/{section}")
        async def config_patch(section: str, request: Request) -> JSONResponse:
            """Set one routing-policy value for new work — no restart.

            The value is validated by the loader's own parser (`policy_value`),
            so a value a restart would refuse is refused here with the same
            sentence. A weight is the exception that needs care: it applies to
            new threads only, so a change that would place running
            conversations differently answers 409 with the count and does
            nothing until the body carries `"confirm": true`.
            """
            denied = self._require_admin(request)
            if denied is not None:
                return denied
            target = policy_target(section)
            if target is None:
                # 403 and not 404: the field is part of the configuration, it is
                # simply not a value the page may set. The message says why.
                return _policy_error(403, "not_editable", section,
                                     policy_refusal(section))
            if target[0] == "hosts" and self.cfg.host(target[1]) is None:
                # The grammar is right, the machine is not part of the fleet —
                # a path that does not resolve, so 403 with the names we do have.
                return _policy_error(403, "not_editable", section,
                                     f"{section}: no host {target[1]!r} — the fleet "
                                     f"declares "
                                     f"{', '.join(h.name for h in self.cfg.hosts) or 'none'}")
            try:
                body = await request.json()
            except ValueError:
                return _policy_error(400, "invalid_value", section,
                                     "a JSON body {'value': ...} is required")
            if not isinstance(body, dict) or "value" not in body:
                return _policy_error(400, "invalid_value", section,
                                     "a 'value' is required")
            try:
                value = policy_value(self.cfg, section, body["value"])
            except ConfigError as exc:
                # `str(exc)`, not a rewritten sentence: the point of the issue is
                # that the page and the start-up log say the same thing.
                return _policy_error(400, "invalid_value", section, str(exc))

            if target[0] == "hosts" and target[2] == "weight":
                moving = threads_that_would_move(self.fleet, self.cfg, self.registry,
                                                 {target[1]: value})
                if moving and body.get("confirm") is not True:
                    return JSONResponse({
                        "error": "confirm_required",
                        "path": section,
                        "threads_that_would_move": moving,
                        "message": (f"{moving} live thread(s) would be placed on a "
                                    f"different host under the new split; a weight "
                                    f"applies to new threads only, so nothing moved "
                                    f"yet — send \"confirm\": true to apply it"),
                    }, status_code=409)

            self.overlay.set_path(section, value)
            save_overlay(self.overlay)
            policy_assign(self.cfg, section, value)
            # `/config` says where each value comes from; refresh the view the
            # page reads before answering, so a poll right after the click
            # cannot show the old origin.
            self.cfg.overrides = self.overlay.paths()
            log.warning("config_policy_set path=%s value=%r by=%s", section, value,
                        self.client_address(request) or "-")
            return JSONResponse({"path": section, "value": value,
                                 "source": "overlay",
                                 "effective": policy_read(self.cfg, section)})

        @app.delete("/admin/config/{section}")
        async def config_delete(section: str, request: Request) -> JSONResponse:
            """Drop one override; the file's value comes back into force.

            Idempotent: a path the overlay does not set is a 200 with
            `source: "config"`, because "there is no override" is exactly the
            state the operator asked for.
            """
            denied = self._require_admin(request)
            if denied is not None:
                return denied
            target = policy_target(section)
            if target is None:
                return _policy_error(403, "not_editable", section,
                                     policy_refusal(section))
            if target[0] == "hosts" and self.cfg.host(target[1]) is None:
                return _policy_error(403, "not_editable", section,
                                     f"{section}: no host {target[1]!r} — the fleet "
                                     f"declares "
                                     f"{', '.join(h.name for h in self.cfg.hosts) or 'none'}")
            if self.overlay.drop_path(section):
                save_overlay(self.overlay)
                # The baseline was taken before the overlay was merged, so it is
