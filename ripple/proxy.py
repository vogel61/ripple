        @app.delete("/admin/threads/{key}")
        async def thread_delete(key: str, request: Request) -> JSONResponse:
            """Give a thread's slot back now instead of waiting for its TTL (#35).

            A thread holds its host's slot for `affinity.ttl_seconds` after its
            last request and nothing else could end that early — the page could
            only watch the countdown. The `key` in the path is the `label` the
            page shows, i.e. what `/healthz → threads.registry[].key` carries, so
            it is resolved *against the registry* and never re-derived from a
            hash: a `sid:` id longer than `LABEL_CHARS` arrives here cut to the
            label, and only the registry knows the whole key. The full key is
            accepted as well, so an operator with `curl` and `/stats` does not
            have to cut it first.

            A thread with a request in flight owns its slot: pulling it out from
            under a running request is exactly what the reservation exists to
            prevent (see `ThreadRegistry.evictable`), so that case is a 409 that
            names the host and the count — never a silent drop.
            """
            denied = self._require_admin(request)
            if denied is not None:
                return denied
            thread = self.registry.threads.get(key)
            if thread is None:
                same = [t for t in self.registry.threads.values() if t.label == key]
                if len(same) > 1:
                    # Two threads share the visible label; a delete that picked
                    # one of them would be a guess about someone's cache.
                    return JSONResponse({"error": {"message": (
                        f"{key} names {len(same)} threads — send the full key")}},
                        status_code=409)
                thread = same[0] if same else None
            if thread is None:
                return JSONResponse({"error": {"message": f"unknown thread {key}"}},
                                    status_code=404)
            if thread.active > 0:
                return JSONResponse({"error": {"message": (
                    f"thread {thread.label} has {thread.active} request(s) in "
                    f"flight on {thread.host}")}}, status_code=409)
            self.registry.remove(thread)
            self.stats.threads_deleted += 1
            log.warning("thread_deleted key=%s host=%s turns=%d idle=%.0fs by=%s",
                        thread.label, thread.host, thread.turns,
                        time.time() - thread.last_seen,
                        self.client_address(request) or "-")
            return JSONResponse({"key": thread.label, "removed": True,
                                 "host": thread.host,
                                 "slot_freed": bool(thread.holds_slot)})

