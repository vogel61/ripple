        @app.post("/admin/restart")
        async def restart_post(request: Request) -> JSONResponse:
            """End this process and let launchd start it again. 202 = accepted."""
            denied = self._require_admin(request)
            if denied is not None:
                return denied
            client = self.client_address(request) or "?"
            state = self.restart_state()
            if not state["supervised"]:
                # The cause is in the log as well as in the sentence, so a
                # refused click at 03:00 says *which* fact was missing (#27).
                # `supervision_state` is asked again only for that word: the
                # ownership query behind it is memoised, so this costs nothing.
                log.warning("restart_refused reason=unsupervised cause=%s client=%s "
                            "inflight=%d", supervision_state()["cause"], client,
                            state["inflight"])
                # `**state` carries `reason_code` and `reason_params` beside the
                # sentence: the page translates the cause (#29) and keeps
                # `error.message` as the tooltip.
                return JSONResponse(
                    {"error": {"message": state["reason"],
                               "code": "restart_unsupervised"},
                     **state}, status_code=503)
            if state["pending"]:
                # A second click is not an error: the restart it asks for is
                # already on its way. Answering 202 again keeps the dialog
                # honest and keeps the log at one line per restart.
                return JSONResponse({"accepted": True, **state}, status_code=202)
            body = await _json_body(request)
            # `force` is a *boolean acknowledgement*, never a command: the
            # endpoint executes nothing, so there is no string to interpolate
            # into a shell. `true`/`1`/`yes`/`on` are accepted where the
            # dashboard sends a body and where a human types a query.
            forced = (bool(body.get("force"))
                      or (request.query_params.get("force") or "").strip().lower() in _TRUE)
            inflight = state["inflight"]
            if inflight > 0 and not forced:
                # The drain warning, enforced: the operator's own streaming
                # session runs through this service, so a restart with work in
                # flight needs the explicit second confirmation.
                log.warning("restart_refused reason=inflight client=%s inflight=%d hosts=%s",
                            client, inflight, ",".join(state["hosts"]))
                # `**state` carries `reason_code: inflight` (#29): the page says
                # why in its own language and quotes this sentence as the
                # tooltip — it still names the streaming session and `force=1`.
                return JSONResponse(
                    {"error": {
                        "message": f"{inflight} request(s) are still in flight "
                                   f"({', '.join(state['hosts'])}) — the one that is "
                                   f"streaming right now ends with the process. "
                                   f"Repeat with force=1 to restart anyway.",
                        "code": "restart_inflight"},
                     **state}, status_code=409)
            log.warning("restart_requested by=dashboard client=%s inflight=%d",
                        client, inflight)
            self._restart_task = asyncio.create_task(
                self._restart_after(self.restart_delay, inflight))
            return JSONResponse({"accepted": True, **self.restart_state()},
                                status_code=202)

