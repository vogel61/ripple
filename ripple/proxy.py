        @app.post("/admin/nodes/{name}/replicate")
        async def replicate(name: str, request: Request) -> JSONResponse:
            """Copy one model from `source` to this node. 202 = started."""
            denied = self._require_admin(request)
            if denied is not None:
                return denied
            host = self.fleet.get(name)
            if host is None:
                return JSONResponse({"error": {"message": f"unknown node {name!r}"}},
                                    status_code=404)
            body = await _json_body(request)
            source = str(body.get("source") or "").strip()
            model = str(body.get("model") or "").strip()
            overwrite = bool(body.get("overwrite")) or \
                (request.query_params.get("overwrite") or "").strip().lower() in _TRUE
            running = rep_tasks.get(name)
            if running is not None and not running.done():
                # Keyed on the task: the job's state string is not enough, the
                # cleanup after `done` still writes to the machine.
                return JSONResponse(
                    {"error": {"message": f"a replication to {name} is already running"}},
                    status_code=409)

            plan, transport, src_ep, tgt_ep = await self.replication_plan(
                source, name, model, overwrite)
            if not plan.ok:
                log.warning("replication_refused target=%s source=%s model=%s errors=%s",
                            name, source, model, " | ".join(plan.errors))
                return JSONResponse(
                    {"error": {"message": "; ".join(plan.errors)},
                     "plan": plan.as_dict()}, status_code=409)

            job = replication.new_job(plan)
            job["id"] = str(uuid.uuid4())
            rep_jobs[name] = job
            cancel = asyncio.Event()
            rep_cancel[name] = cancel
            # The window belongs to this job and is not persisted: if RIPPLE dies
            # mid-copy the node has to come back by itself. An operator window is
            # never touched.
            state = {"window": False}

            def open_window() -> None:
                if host.maintenance is None:
                    self.maintenance.set(name, by="replication",
                                         note=f"job {job['id']}")
                    self._apply_windows()
                    state["window"] = True
                    log.info("replication_maintenance node=%s (out of service for "
                             "the job)", name)

            def close_window() -> None:
                if state["window"] and self.maintenance.clear(name):
                    self._apply_windows()
                    log.info("replication_maintenance_clear node=%s", name)

            task = asyncio.create_task(replication.run_job(
                job=job, plan=plan, transport=transport, source=src_ep,
                target=tgt_ep, factor=self.cfg.replication.free_space_factor,
                exclude=self.cfg.replication.settings_exclude,
                verify_settings=self.cfg.replication.verify_settings,
                cancel=cancel, open_window=open_window, close_window=close_window,
            ), name=f"ripple-replicate-{name}")
            rep_tasks[name] = task
            task.add_done_callback(lambda _t, n=name: rep_tasks.pop(n, None))
            log.warning("replication_started source=%s target=%s model=%s size=%.1fGB "
                        "free=%.1fGB job=%s", source, name, model,
                        plan.size_bytes / 1e9,
                        (plan.free_bytes or 0) / 1e9, job["id"])
            return JSONResponse({"job": job["id"], "source": source, "target": name,
                                 "model": model, "plan": plan.as_dict(),
                                 "job_state": job}, status_code=202)

