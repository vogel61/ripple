    async def _update_check(self) -> None:
        """Ask once whether a newer release exists, then never again (issue #123).

        One task, one answer, no retry loop and no polling: the operator asked
        for a start-up check, and a dashboard that keeps calling an API nobody
        is watching would be a background cost with no reader. The state is
        written in one assignment, so `/healthz` sees either the old answer or
        the new one, never half of it.

        Only `newer` logs — that is a fact worth having in the log. `unknown`
        and `current` are silent by contract: a hint that failed must not turn
        into an error line on every start, and a machine ahead of the last
        release (a GitHub checkout, handover §5) must not be told to go back.
        """
        try:
            state = await update_check.check(
                self.cfg.update.url, __version__,
                timeout=self.cfg.update.timeout_seconds, enabled=True)
        except asyncio.CancelledError:
            raise
        except Exception:                 # noqa: BLE001 — never kill the task log
            log.debug("update check failed", exc_info=True)
            state = update_check.UpdateState()
        self.update_state = state
        if state.state == "newer":
            log.info("RIPPLE %s is released (running %s) — `ripple update`",
                     state.latest, __version__)

    async def _purge_loop(self) -> None:
        while True:
            try:
                await asyncio.sleep(30)
                gone = self.registry.purge()
                if gone:
                    log.info("thread_ttl purged=%d active=%d", gone,
                             self.registry.active_total())
                # A maintenance window with `minutes` ends by itself; the node must
                # come back without the operator having to remember it.
                expired = self.maintenance.prune()
                if expired:
                    save_maintenance(self.maintenance)
                    self._apply_windows()
                    log.info("maintenance_expired nodes=%s", ",".join(expired))
            except asyncio.CancelledError:
                return
            except Exception:  # noqa: BLE001
                log.exception("purge loop error")

    # -- the placement optimizer (issue #80) -------------------------------
    def start_optimizer(self) -> asyncio.Task | None:
        """Start the periodic decision. `placement.optimizer.enabled: false` → no task.

        Started beside the other background tasks, never in the request path: a
        move decided while a request is being admitted either throws that
        request's work away or blocks it. The interval is
        `placement.optimizer.interval_seconds`; one scan moves at most one
        thread, and the next scan is 30 s later.
        """
        if not self.cfg.placement.optimizer.enabled:
            log.info("optimizer disabled (placement.optimizer.enabled=false)")
            return None
        if self._optimizer_task is None or self._optimizer_task.done():
            self._optimizer_task = asyncio.create_task(
                self._optimizer_loop(), name="ripple-optimizer")
        return self._optimizer_task

    async def _optimizer_loop(self) -> None:
        interval = max(1.0, float(self.cfg.placement.optimizer.interval_seconds))
        while True:
            try:
                await self.optimize_once()
            except asyncio.CancelledError:
                raise
            except Exception:  # noqa: BLE001 — the loop must never die
                log.exception("optimizer loop error")
            try:
                await asyncio.sleep(interval)
            except asyncio.CancelledError:
                return

    def optimizer_moves_last_hour(self, now: float | None = None) -> int:
        """Moves this optimizer made in the last hour (its own budget, not rebind's)."""
        now = now if now is not None else time.time()
        while self._optimizer_moves and now - self._optimizer_moves[0] > 3600:
            self._optimizer_moves.popleft()
        return len(self._optimizer_moves)

    async def optimize_once(self, now: float | None = None) -> RebindPlan:
        """One scan: ask `plan_rebind`, then move the thread it named.

        The move is the existing bookkeeping — `registry.note_rebind` (which
        stamps `last_rebind`, so the thread cannot move twice inside the
        cooldown), the `threads_rebound` counter and the log line with the
        numbers the decision used. Nothing is re-decided here: the plan is the
        verdict, and a plan without `dst` is a decision to stay.
        """
        opt = self.cfg.placement.optimizer
        moment = time.time() if now is None else now
        if not opt.enabled:
            return RebindPlan(reason="disabled",
                              detail="placement.optimizer.enabled is false")
        used = self.optimizer_moves_last_hour(moment)
        if opt.max_moves_per_hour and used >= opt.max_moves_per_hour:
            log.debug("optimizer_skip reason=budget detail=%d/%d moves this hour",
                      used, opt.max_moves_per_hour)
            return RebindPlan(reason="budget",
                              detail=f"{used}/{opt.max_moves_per_hour} moves this hour")

        async with self._lock:
            plan = plan_rebind(self.fleet, self.cfg, self.registry, now=moment)
            # One sample per scan, for the arriving turn's deadband (issue #95):
            # `Δtotal` is the same number `decide_migration` compares, and its
            # spread over the last `migrate.band_samples` scans is the only
            # honest band. A scan that could not evaluate it contributes
            # nothing — a fabricated zero would shrink the band.
            if plan.delta_total is not None:
                self._delta_history.append(float(plan.delta_total))
            if not plan.moves or plan.thread is None or plan.dst is None:
                # The number that decided it, when there was one: `Δtotal ≤ 0`
                # is a measurement, not silence.
                log.debug("optimizer_skip reason=%s delta_total=%s detail=%s",
                          plan.reason,
                          "n/a" if plan.delta_total is None else f"{plan.delta_total:+.1f}",
                          plan.detail or "-")
                return plan
            self.registry.note_rebind(plan.thread, plan.dst, now=moment)
            self._optimizer_moves.append(moment)
            self.stats.threads_rebound += 1
            # One line per move — a move is an event, not noise.
            log.warning("rebind thread=%s src=%s dst=%s delta_total=%+.1f "
                        "gain_seconds=%.1f cost_seconds=%.1f model=%s",
                        plan.thread.label, plan.src, plan.dst,
                        plan.delta_total or 0.0, plan.gain_seconds,
                        plan.cost_seconds, plan.model)
        return plan

    # -- the arriving turn (issue #95, §6.4) -------------------------------
    def cold_pp_tps(self, host: str) -> float | None:
        """The prefill rate this node was measured at on **cold** prompts.

        `prompt_tokens_per_second` is only a prefill rate when the prompt was
        not cached: on a 700/702-token hit the server reports 14.46 tok/s
        because it prices the two uncached tokens, against 1254 tok/s on a cold
        prompt of the same size. A mean over both would understate the node by
        two orders of magnitude and make every move look free, so only rows
        whose `cached_tokens` is ~0 count (`COLD_PP_CACHE_RATIO`), and only for
        prompts long enough that the rate is not mostly fixed overhead
        (`COLD_PP_MIN_TOKENS`).

        A row that does not state `cached_tokens` counts: a server that never
        reports it also prices the whole prompt, so its number *is* the cold
        rate. A row that states a hit never counts, whatever its rate.

        `None` means "not measured" — the caller keeps the configured
        `pp_tps` / `default_pp_tps` rather than inventing one.
        """
        row = self.usage.hosts.get(host)
        if row is None:
            return None
        rates: list[float] = []
        for observation in row.history:
            rate = observation.get("prompt_tokens_per_second")
            prompt = int(observation.get("prompt_tokens") or 0)
            cached = observation.get("cached_tokens")
            if rate is None or float(rate) <= 0.0 or prompt < COLD_PP_MIN_TOKENS:
                continue
            if cached is not None and int(cached) > max(1, int(COLD_PP_CACHE_RATIO * prompt)):
                continue
            rates.append(float(rate))
        if not rates:
            return None
        return round(sum(rates) / len(rates), 1)

    def migration_view(self, model: str) -> MigrateFleet:
        """`fleet_view`, with each node's `pp_tps` replaced where it was measured.

        The configured `pp_tps` is a constant from the day it was taken; the
        ledger has the same node's rate from requests this process actually
        served. The measurement wins when it exists, because the whole point of
        the price is `prompt_tokens / pp_tps` — and `fleet_view`'s own fallback
        (per-host `pp_tps`, then `rebind.default_pp_tps`, then "no price") is
        untouched for a node the ledger has never seen cold.
        """
        view = fleet_view(self.fleet, self.cfg, self.registry, model,
                          delta_history=tuple(self._delta_history))
        hosts = {}
        for name, entry in view.hosts.items():
            measured = self.cold_pp_tps(name)
            hosts[name] = entry if measured is None else replace(entry, pp_tps=measured)
        return MigrateFleet(hosts=hosts, delta_history=view.delta_history)

    def _migrate_arriving_turn(self, thread, model: str, prompt_tokens: int, *,
                               now: float, last_seen: float,
                               completion_tokens: int) -> MigrationDecision | None:
        """Should *this* turn move the thread? `None` when the feature is off.

        §6.4's decision, asked where it can still be acted on: the prompt is in
        hand and is about to be prefilled in full wherever it lands. The thread
        is handed over as values (`ThreadState`) and the fleet as values
        (`MigrateFleet`), so the decision cannot read a live object and cannot
        write one — the caller applies the verdict.

        `last_seen` is the arrival time of the *previous* turn, captured before
        `registry.touch` refreshed it: the idle time so far is what shortens
        the slot's remaining life, and `ttl_remaining_s` is what bounds
        `turns_left` by the horizon.

        The fleet-wide budget is `rebind.max_per_hour` — the same hour, the same
        moves, whichever of the two halves of the calculus spends them.
        """
        if not self.cfg.placement.migrate.enabled:
            return None
        state = ThreadState(
            host=thread.host,
            turns=thread.turns,
            created=thread.created,
            last_turn_at=last_seen,
            ttl_remaining_s=max(0.0, self.registry.ttl_of(thread) - max(0.0, now - last_seen)),
            moved_from=thread.moved_from,
            moved_at=thread.moved_at,
            pinned_until=thread.pinned_until,
            move_count=thread.move_count,
            kind=thread.kind,
        )
        return decide_migration(
            cfg=self.cfg, thread_state=state, fleet=self.migration_view(model),
            prompt_tokens=prompt_tokens, now_s=now,
            assumed_completion_tokens=completion_tokens,
            moves_last_hour=self.registry.rebinds_last_hour(now),
            max_moves_per_hour=int(self.cfg.placement.rebind.max_per_hour or 0),
        )

    def _note_migration(self, thread, host: str, decision: MigrationDecision, *,
                        now: float) -> None:
        """Write a `moved` verdict back onto the thread.

        `registry.note_rebind` is the move itself (host, `last_rebind`, the
        fleet's hour budget) — the same bookkeeping the sweep uses, because it
        is the same fleet budget. The three fields the arriving-turn decision
        keeps for itself are its hysteresis: where it came from (`moved_from`,
        so a return is priced up), when (`moved_at`, which opens the cooldown
        and the pin window), and how often (`move_count`, which earns the pin).
        `pinned_until` is taken from `priced["pin_until"]` when the decision
        priced one — the move that spends the last of the window's budget pins
        the thread for the rest of it.
        """
        window = float(self.cfg.placement.migrate.window_seconds)
        count = (thread.move_count
                 if thread.moved_at > 0.0 and (now - thread.moved_at) < window else 0)
        previous = thread.host
        self.registry.note_rebind(thread, host, now=now)
        thread.moved_from = previous
        thread.moved_at = now
        thread.move_count = count + 1
        thread.pinned_until = float(decision.priced.get("pin_until") or 0.0)

    # -- per-host ledger (issue #33) ---------------------------------------
    def start_host_stats(self) -> asyncio.Task:
        """Start the sampler. Called from the lifespan; a test may call it too.

        It runs on the probe tick (`discovery.interval_seconds`), because the
        state it samples is the state the probes already ask about: one extra
        call per host per tick, and nothing on the request path.
        """
        if self._host_stats_task is None or self._host_stats_task.done():
            self._host_stats_task = asyncio.create_task(
                self._host_stats_loop(), name="ripple-host-stats")
        return self._host_stats_task

    async def _host_stats_loop(self) -> None:
        interval = max(1.0, float(self.cfg.discovery.interval_seconds))
        while True:
            try:
                await self._sample_hosts()
            except asyncio.CancelledError:
                raise
            except Exception:  # noqa: BLE001 — the loop must never die
                log.exception("host_stats loop error")
            try:
                await asyncio.sleep(interval)
            except asyncio.CancelledError:
                return

    async def _sample_hosts(self) -> None:
        """One tick: the state of every host, then the cross-check, then a flush.

        A host that does not answer contributes no *new* observation — the
        interval is charged to the state it was last seen in, and a host that
        never answered stays out of the ledger entirely. The tick is never turned
        into `idle` for a node whose answer was missing, for the same reason a
        request without usage is not split by estimate.
        """
        states: dict[str, str] = {}
        for host in self.fleet.hosts:
            state = await self._activity_state(host)
            if state is not None:
                states[host.cfg.name] = state
        self.host_stats.sample(states)
        if time.time() - self._cross_at >= self._cross_interval():
            await self._refresh_cross()
        self.host_stats.flush()

    def _cross_interval(self) -> float:
        """How often the nodes' own SQLite count is re-read.

        Not on every tick: `GET /admin/api/usage` reads a database, and the
        cross-check is a sanity figure for a window of hours, not a live value.
        """
        return max(60.0, float(self.cfg.discovery.interval_seconds))

    async def _activity_state(self, host: HostRuntime) -> str | None:
        """`GET /admin/api/activity` on one node, mapped to one state.

        The oMLX admin key is the one already in the configuration
        (`replication.admin_key`, per host overridable) — it is valid on both
        nodes and is not the client key RIPPLE passes through.
        """
        endpoint = replication.endpoint_for(host, self.cfg)
        if not endpoint.api_base:
            return None
        if not endpoint.api_key:
            if not self._activity_warned:
                self._activity_warned = True
                log.warning("host_stats: no oMLX admin key (replication.admin_key) — "
                            "the per-host state sampling stays blind")
            return None
        try:
            resp = await self.proxy_client.get(
                endpoint.api_base.rstrip("/") + "/admin/api/activity",
                headers={"authorization": f"Bearer {endpoint.api_key}"},
                timeout=self.cfg.discovery.timeout_seconds)
            payload = resp.json()
        except (httpx.HTTPError, ValueError, OSError) as exc:
            log.debug("host_stats activity host=%s failed: %s", host.cfg.name, exc)
            return None
        if resp.status_code >= 400:
            log.debug("host_stats activity host=%s status=%d", host.cfg.name,
                      resp.status_code)
            return None
        return state_from_activity(payload)

    async def _refresh_cross(self) -> None:
        """Read the nodes' own count (`?range=today`) as the cross-check.

        It is shown *beside* the ledger, never added to it: the gap between the
        two is the traffic that went past RIPPLE, and that is the point.
        """
        rows: list[dict[str, Any]] = []
        error: str | None = None
        for host in self.fleet.hosts:
            endpoint = replication.endpoint_for(host, self.cfg)
            entry: dict[str, Any] = {"name": host.cfg.name}
            if not endpoint.api_base or not endpoint.api_key:
                entry.update({"requests": 0, "prefill_seconds": 0.0,
                              "generation_seconds": 0.0})
                rows.append(entry)
                error = error or "no oMLX admin key configured"
                continue
            try:
                resp = await self.proxy_client.get(
                    endpoint.api_base.rstrip("/") + "/admin/api/usage",
                    params={"range": "today"},
                    headers={"authorization": f"Bearer {endpoint.api_key}"},
                    timeout=max(5.0, self.cfg.discovery.timeout_seconds))
                payload = resp.json()
            except (httpx.HTTPError, ValueError, OSError) as exc:
                entry.update({"requests": 0, "prefill_seconds": 0.0,
                              "generation_seconds": 0.0})
                rows.append(entry)
                error = error or f"{host.cfg.name}: {type(exc).__name__}"
                continue
            totals = cross_from_usage(payload) if resp.status_code < 400 else None
            if totals is None:
                error = error or f"{host.cfg.name}: HTTP {resp.status_code}"
                totals = {"requests": 0, "prefill_seconds": 0.0,
                          "generation_seconds": 0.0}
            entry.update(totals)
            rows.append(entry)
        self._cross_at = time.time()
        self.host_stats.set_cross(rows, range_name="today", at=self._cross_at,
                                  error=error)
        if error:
            log.debug("host_stats cross-check incomplete: %s", error)

    # -- request handling --------------------------------------------------
    async def handle(self, request: Request, path: str) -> Response:
        t0 = time.perf_counter()
        # Where the request came from, for the log and the decision ring buffer
        # (FA-14). Resolved once: the same address must appear on the request
        # line and on the error line it may end in.
        client = self.client_address(request)
        client_key, denied = self._authenticate(request)
        if denied is not None:
            return denied
        try:
            body = await request.json()
        except (ValueError, json.JSONDecodeError):
            return JSONResponse({"error": {"message": "invalid JSON body",
                                           "type": "invalid_request_error"}}, status_code=400)
        if not isinstance(body, dict):
            return JSONResponse({"error": {"message": "body must be a JSON object",
                                           "type": "invalid_request_error"}}, status_code=400)

        model = body.get("model")
        if not model:
            return JSONResponse({"error": {"message": "field 'model' is required",
                                           "type": "invalid_request_error"}}, status_code=400)
        if client_key is not None and not client_key.model_allowed(str(model)):
            # OpenAI answers a model the caller may not use with 404, not 403 —
            # the model is simply not there for this key.
            return JSONResponse({"error": {"message": f"model {model!r} not found",
                                           "type": "invalid_request_error",
                                           "code": "model_not_found"}}, status_code=404)
        stream = bool(body.get("stream"))
        # Two different texts, on purpose (issue #14): `text` is what the user
        # wrote and stays the input of the prefix match; `prompt_tokens` is the
        # size of the *whole* request — system prompt, history, tool schema —
        # and is what decides "ephemeral", the prefill bias and the rebind cost.
        # Sized from `text` alone, an 83 k-token Hermes turn looked like 27
        # tokens.
        text = prompt_text(body)
        prompt_chars = len(text)
        prompt_tokens = estimate_tokens(prompt_size_text(body))
        self.stats.requests_total += 1
        # FA-14: the placement layer's own note for this request ("prefill bias
        # beta -0.29", "all hosts at spill_threshold", "evicts idle …"). It is
        # the only place a bias-driven decision can be seen as a reason.
        decision_note: str | None = None
        # Set when the placement layer said the model has to be loaded on the host
        # that is about to receive the request; consumed once, right before the
        # dispatch, to suspend that host's probes for the duration.
        cold_load = False

        # The traffic class of the key decides three things below: the TTL of a
        # new thread (batch), whom an eviction takes (interactive) and whether
        # this request may hold a slot at all (one-shot).
        kind = client_key.kind if client_key is not None else "interactive"
        one_shot = kind == "one-shot"
        if one_shot:
            # A one-shot request never binds a thread and never takes a slot,
            # however large the prompt is. It also must not adopt an existing
            # thread — that would bind it by the back door and keep its cache
            # warm for traffic that never comes back. The identity is still read
            # (never registered) so `consistent_hash` spreads these requests
            # instead of sending every one of them to the same host.
            key, source, thread = (
                self.registry.key_from_headers(request.headers.items())
                or f"anon:{fingerprint(model, body) or 'x'}"), "one-shot", None
            self.stats.requests_one_shot += 1
        else:
            key, source, thread = self._identify(request, body, model, text)
        ephemeral = one_shot or self._is_ephemeral(body, prompt_tokens)

        async with self._lock:
            if thread is not None and source == "prefix_match" and kind == "interactive":
                # The conversation was opened by a batch key, a person is now
                # waiting on it: a 120 s batch TTL would drop the prefix cache
                # under a running conversation. Promotion is one-way (there is
                # no demotion) and `promote` reports only the real change, so
                # the counter and the log line appear exactly once per thread.
                if self.registry.promote(thread):
                    self.stats.threads_promoted += 1
                    log.info("promote thread=%s batch->interactive", thread.label)
            if thread is not None:
                host = self.fleet.get(thread.host)
                ok, why = (admit(self.fleet, host, model) if host else (False, "host gone"))
                if ok:
                    # The size of *this* request is the price of moving the
                    # thread: one prefill of the next prompt. The registry
                    # overwrites it, never adds — the number of turns says
                    # nothing about the size (issue #80).
                    previous_seen = thread.last_seen
                    self.registry.touch(thread, prompt_tokens=prompt_tokens)
                    reason = "thread"
                    self.stats.thread_hits += 1
                    # §6.4 (issue #95): the turn is arriving, its prompt is in
                    # hand, and it is about to be prefilled in full wherever it
                    # lands — the one moment a move can still be paid for. The
                    # decision is priced here and applied below; a refusal keeps
                    # the dispatch on `thread.host` exactly as before and only
                    # changes the reason the operator reads.
                    moment = time.time()
                    completion = body.get("max_tokens")
                    migration = self._migrate_arriving_turn(
                        thread, model, prompt_tokens, now=moment,
                        last_seen=previous_seen,
                        completion_tokens=(int(completion)
                                           if isinstance(completion, int) and completion > 0
                                           else int(self.cfg.placement.rebind
                                                    .assumed_completion_tokens or 400)))
                    if migration is not None:
                        decision_note = _migration_note(migration)
                        target = (self.fleet.get(migration.host)
                                  if migration.moves else None)
                        if target is not None and target is not host:
                            # `admit` is the last word, exactly as for a stay: a
                            # destination that filled up between the fleet view
                            # and here must not receive a thread whose cache it
                            # would then throw away.
                            dst_ok, dst_why = admit(self.fleet, target, model)
                            if dst_ok:
                                self._note_migration(thread, target.cfg.name,
                                                     migration, now=moment)
                                host = target
                                reason = "moved"
                                self.stats.threads_rebound += 1
                                log.warning("migrate thread=%s from=%s to=%s %s",
                                            thread.label, thread.moved_from,
                                            target.cfg.name, decision_note)
                            else:
                                decision_note += f" move_refused={dst_why}"
                        elif migration.moves:
                            # The decision named the host the thread is already
                            # on; nothing to apply, and `thread` is the truth.
                            decision_note += " move_noop"
                        else:
                            # A refusal is not silence: the reason names what
                            # stopped the move (`no_repayment`,
                            # `gain_below_band`, `pinned`, `cooldown`,
                            # `cost_exceeds_ttl`, …) whenever the calculus
                            # actually ran. `no_curve`/`no_target` are the
                            # exception, and on purpose: they say the fleet
                            # could not price this turn at all (no curve, or no
                            # other host), which is not a fact about the turn —
                            # `thread` stays true and the note on the same line
                            # carries the reason, so nothing is hidden and a
                            # fleet without measurements reads exactly as
                            # before.
                            if migration.reason not in _UNPRICED_REASONS:
                                reason = migration.reason
                elif (host is not None and host.in_pool and host.cfg.enabled
                      and host.model_available(model)):
                    # The bound node is in the pool but saturated. Moving the
                    # thread would cost the prefix cache — wait instead
                    # (FA-9/§6.1). A degraded bound host is in the pool: refusing
                    # here would turn one missed probe into a 503.
                    #
                    # `model_available` belongs in this condition (issue #11): a
                    # model the operator disabled on this node is not a reason to
                    # wait, it is a reason to fall back to the host that still
                    # offers it — which is what the `else` below does.
                    return self._error(None, model, t0, prompt_chars, thread.label,
                                       prompt_tokens=prompt_tokens,
                                       client=client, thread_source=_thread_source(thread, source),
                                       status=503, message=why or "host saturated",
                                       retry_after=1)
                else:
                    # FA-11: the bound node is gone → fallback, rebind, log it.
                    decision = choose(self.fleet, self.cfg, self.registry, model,
                                      thread_key=thread.key,
                                      exclude=frozenset({thread.host}),
                                      prompt_tokens=prompt_tokens)
                    if decision.host is None:
                        return self._error(decision, model, t0, prompt_chars,
                                           thread.label,
                                           prompt_tokens=prompt_tokens,
                                           client=client,
                                           thread_source=_thread_source(thread, source))
                    host = decision.host
                    self._count_bias(decision)
                    decision_note = decision.note
                    cold_load = _needs_cold_load(decision)
                    self._evict_slot(decision)
                    self.registry.rebind(thread, host.cfg.name)
                    reason = "fallback"
                    self.stats.fallbacks += 1
                    log.warning("fallback thread=%s from=%s to=%s (%s)",
                                thread.label, thread.host, host.cfg.name, why)
            else:
                decision = choose(self.fleet, self.cfg, self.registry, model,
                                  thread_key=key or "", kind=kind,
                                  holds_slot=not one_shot,
                                  prompt_tokens=prompt_tokens)
                if decision.host is None:
                    return self._error(decision, model, t0, prompt_chars, None,
                                       prompt_tokens=prompt_tokens,
                                       client=client,
                                       thread_source=_thread_source(thread, source))
                host = decision.host
                self._count_bias(decision)
                decision_note = decision.note
                cold_load = _needs_cold_load(decision)
                self._evict_slot(decision)
                # The reason the placement layer decided on is the reason the
                # operator must see (FA-14). A one-shot request is labelled by its
                # class instead: it never reserved anything, so how it was placed
                # says less than the fact that it is ephemeral by contract. The
                # placement counters keep counting either way.
                if cold_load:
                    # Counted from the tier, not from the reason: a degraded host
                    # that has to load carries the reason `degraded_host`, and the
                    # load it causes is still a load RIPPLE supervised.
                    self.stats.cold_load += 1
                # `evict_idle` is the *subset* of those loads that had to unload
                # an idle model first — a separate `if`, not an `elif`: an
                # `evict_idle` tier is a cold load too, so one request moves both
                # counters. Counted from the tier again, for the same reason as
                # above.
                if _evicts_idle(decision):
                    self.stats.evict_idle += 1
                if one_shot:
                    reason = "one_shot"
                elif decision.reason in ("cold_load", "evict_idle", "model_pinned",
                                         "slot_evict", "degraded_host"):
                    reason = decision.reason
                else:
                    reason = "new_thread" if not ephemeral else "ephemeral"
                if ephemeral:
                    # No slot, and the load signal is written when the request is
                    # *done* (see the release below), not here: an entry noted at
                    # dispatch expires after 60 s, and a request that generates
                    # for 225 s then became invisible while it was still running
                    # (issue #14, cause 3).
                    thread = None
                else:
                    thread = self.registry.register(
                        key=key or f"anon:{fingerprint(model, body) or 'x'}",
                        model=model, host=host.cfg.name, text=text,
                        holds_slot=True, source=source, kind=kind,
                        # Who holds the slot is a fact about the opener: the
                        # name stays with the thread even after a prefix match
                        # adopted it (issue #32).
                        key_name=client_key.name if client_key is not None else None,
                        # A batch thread carries its own, shorter TTL; every
                        # other thread keeps the global one.
                        ttl_seconds=(self.cfg.affinity.batch_ttl_seconds
                                     if kind == "batch" else None),
                        # The prompt size of the opening request — the same
                        # number the request log carries (`prompt_tokens`), so
                        # the price of a move needs no second estimate.
                        prompt_tokens=prompt_tokens)
                    self.stats.threads_new += 1
                if decision.note and "spill" in (decision.note or ""):
                    self.stats.spillover += 1

        # -- dispatch with retry before the first byte (FA-10) -------------
        # oMLX sends no usage inside a stream unless it is asked (it ends with
        # `data: [DONE]`), and without usage there is no decode measurement at all.
        # Ask for it, then strip that extra chunk again before the client sees it.
        client_usage = (isinstance(body.get("stream_options"), dict)
                        and bool(body["stream_options"].get("include_usage")))
        strip_usage = False
        tried: set[str] = set()
        while True:
            if host is None:
                return self._error(None, model, t0, prompt_chars, None,
                                   prompt_tokens=prompt_tokens, client=client,
                                   status=503, message="no host available")
            tried.add(host.cfg.name)
            host.requests_total += 1
            self.stats.host(host.cfg.name)["requests"] += 1
            self.stats.model(model)["requests"] += 1
            # The windowed copy (issue #91): `/healthz → hosts[].requests_by_model`
            # answers "who is serving right now", which the since-start counters
            # cannot. One entry per dispatch, also for a retry hop — that is a
            # second attempt at a node, and the node did receive the request.
            self._request_times.append((time.time(), host.cfg.name, model))
            if not host.acquire():
                return self._error(None, model, t0, prompt_chars,
                                   thread.label if thread else None,
                                   prompt_tokens=prompt_tokens,
                                   client=client,
                                   thread_source=_thread_source(thread, source), status=503,
                                   message=f"{host.cfg.name} at max_inflight")
            # Issue #18: the node is prefilling this model from here until the
            # first token, and generating after it. Counted on the host, so
            # /healthz can say what the machine is doing without asking it —
            # a node in a 26 s prefill answers a probe exactly like an idle one.
            # Set after `acquire()` and released with the slot, so the phase can
            # never outlive the request it belongs to.
            host.begin_phase(model)
            if stream and not client_usage and host.cfg.backend == "omlx":
                body["stream_options"] = {**(body.get("stream_options") or {}),
                                          "include_usage": True}
                strip_usage = True
            if thread is not None:
                self.registry.enter(thread)
            if cold_load:
                # RIPPLE is about to cause this load: suspend the host's probes
                # for its duration (docs/loading-state.md §5.1). Set right before
                # the dispatch so a retry hop begins the state on the new host.
                self._supervise_load(host, model)
                cold_load = False
            resp = None
            try:
                resp, error = await self._forward(host, path, body, stream, request)
            finally:
                # A stream keeps the slot until its body is done: `_forward`
                # returns as soon as the headers are there, and the generation
                # runs for minutes after that. The handover is therefore not a
                # release — `_stream` releases when the last byte is out.
                if not (stream and resp is not None):
                    # The same moment for the phase (issue #18): a request that
                    # never streamed was prefilling for its whole life, and one
                    # that failed never reached a first token.
                    host.end_phase(model, PHASE_PP)
                    host.release()
                    if thread is not None:
                        self.registry.leave(thread)
                    elif ephemeral:
                        # Done: now the ephemeral window starts. While it ran,
                        # `inflight` was the signal; from here the count is.
                        self.registry.note_ephemeral(host.cfg.name, model)
                # The request that caused the load has returned, so the load is
                # over (or has failed) — first of the three end signals. A retry
                # hop lands here too, which ends the state on the old host. Only
                # a load this proxy started is ours to end: a calibration job
                # owns its own entry (source="calibration"), and ending it here
                # would stop the supervision mid-measurement.
                if (host.loading is not None
                        and host.loading.get("model") == model
                        and host.loading.get("source") == "dispatch"):
                    host.end_loading("request_returned")
            if resp is not None:
                break
            # retry only before the first byte, at most one attempt per node
            host.errors_total += 1
            # The node never answered, so this is an error and not a request in
            # the ledger: `requests` counts what the node actually served.
            self.host_stats.error(host.cfg.name)
            self.stats.errors_total += 1
            self.stats.host(host.cfg.name)["errors"] += 1
            if not self.cfg.proxy.retry_other_node or len(tried) >= len(self.fleet.hosts):
                return self._error(None, model, t0, prompt_chars,
                                   thread.label if thread else None,
                                   prompt_tokens=prompt_tokens,
                                   client=client,
                                   thread_source=_thread_source(thread, source), status=502,
                                   message=f"upstream {host.cfg.name} failed: {error}")
            decision = choose(self.fleet, self.cfg, self.registry, model,
                              thread_key=thread.key if thread else "",
                              exclude=frozenset(tried), kind=kind,
                              holds_slot=not one_shot,
                              prompt_tokens=prompt_tokens)
            if decision.host is None:
                return self._error(None, model, t0, prompt_chars,
                                   thread.label if thread else None,
                                   prompt_tokens=prompt_tokens,
                                   client=client,
                                   thread_source=_thread_source(thread, source), status=502,
                                   message=f"upstream {host.cfg.name} failed: {error}")
            self._count_bias(decision)
            decision_note = decision.note
            cold_load = _needs_cold_load(decision)
            log.warning("retry_other_node from=%s to=%s reason=%s", host.cfg.name,
                        decision.host.cfg.name, error)
            host = decision.host
            if thread is not None:
                self.registry.rebind(thread, host.cfg.name)
                reason = "fallback"
                self.stats.fallbacks += 1

        # -- response ------------------------------------------------------
        status = resp.status_code
        if status >= 500:
            self.stats.host(host.cfg.name)["http_5xx"] += 1
            host.http_507_total += 1 if status == 507 else 0
            if status == 503:
                self.stats.http_503_total += 1
        if status >= 400:
            self.stats.errors_total += 1
            self.stats.model(model)["errors"] += 1
        else:
            self.stats.requests_ok += 1

        headers = {"x-ripple-host": host.cfg.name, "x-ripple-reason": reason}
        if thread is not None:
            headers["x-ripple-thread"] = thread.label
        duration_ms = (time.perf_counter() - t0) * 1000.0

        if stream:
            media = resp.headers.get("content-type", "text/event-stream")
            log_request(model=model, host=host.cfg.name, reason=reason,
                        prompt_chars=prompt_chars, prompt_tokens=prompt_tokens,
                        duration_ms=duration_ms, status=status,
                        thread=thread.label if thread else None,
                        thread_source=_thread_source(thread, source), client=client,
                        note=("stream " + (reason if reason else "")).strip(),
                        decision=decision_note)
            self.stats.decision(model=model, host=host.cfg.name, reason=reason,
                                prompt_chars=prompt_chars, prompt_tokens=prompt_tokens,
                                duration_ms=duration_ms,
                                status=status, thread=thread.label if thread else None,
                                thread_source=_thread_source(thread, source), client=client)
            return StreamingResponse(self._stream(resp, host, model,
                                                  strip_usage=strip_usage,
                                                  thread=thread,
                                                  ephemeral=ephemeral,
                                                  status=status),
                                     status_code=status, media_type=media,
                                     headers=headers)

        content = await resp.aread()
        await resp.aclose()
        # The client waited until the last byte, not until the headers: the
        # ledger's `client_seconds` is measured here, after the body arrived.
        self._record_usage(host, model, _json_usage(content),
                           (time.perf_counter() - t0) * 1000.0, status=status,
                           thread=thread)
        log_request(model=model, host=host.cfg.name, reason=reason,
                    prompt_chars=prompt_chars, prompt_tokens=prompt_tokens,
                    duration_ms=duration_ms, status=status,
                    thread=thread.label if thread else None,
                    thread_source=_thread_source(thread, source), client=client,
                    decision=decision_note)
        self.stats.decision(model=model, host=host.cfg.name, reason=reason,
                            prompt_chars=prompt_chars, prompt_tokens=prompt_tokens,
                            duration_ms=duration_ms,
                            status=status, thread=thread.label if thread else None,
                            thread_source=_thread_source(thread, source), client=client)
        out_headers = {k: v for k, v in resp.headers.items()
                       if k.lower() not in HOP_BY_HOP}
        out_headers.update(headers)
        return Response(content=content, status_code=status,
                        media_type=resp.headers.get("content-type", "application/json"),
                        headers=out_headers)

    # -- helpers -----------------------------------------------------------
    # -- client identity (FA-14) -------------------------------------------
    def client_address(self, request: Request) -> str | None:
        """The address the request came from, as far as it can be trusted.

        The transport peer is the only fact a request carries. `X-Forwarded-For`
        is written by whoever sends it, so it is believed **only** when the peer
        is a configured trusted proxy (`proxy.trusted_proxies`, empty = never),
        and then read from the right: the right-most entry is the one that peer
        appended. The left-most entry is what the client wrote about itself,
        which is exactly the part an attacker controls.
        """
        peer = request.client.host if request.client else None
        forwarded = request.headers.get("x-forwarded-for")
        if not forwarded or peer is None or not self._trusted(peer):
            return peer
        for entry in reversed([e for e in forwarded.split(",") if e.strip()]):
            address = _ip(entry)
            if address is not None and not self._trusted(address):
                return address
        # Every hop in the chain is itself a trusted proxy: there is no origin
        # to report, and the peer is the honest answer.
        return peer

    def _trusted(self, address: str) -> bool:
        try:
            ip = ipaddress.ip_address(address)
        except ValueError:
            return False
        return any(ip in net for net in self.trusted_proxies)

    # -- authentication (FA-23) --------------------------------------------
    def _authenticate(self, request: Request) -> tuple[ClientKey | None, Response | None]:
        """401 unless a valid client key is presented. Returns the key for scoping."""
        if not self.cfg.auth.enabled:
            return None, None
        token = _bearer(request)
        key = self.keys.check(token)
        if key is not None:
            self.stats.by_key[key.name] = self.stats.by_key.get(key.name, 0) + 1
            return key, None
        if self.cfg.auth.allow_loopback and _is_loopback(request):
            return None, None
        self.stats.auth_failures += 1
        # The token itself never reaches the log — only the fact that one was
        # rejected and where it came from.
        log.warning("auth_denied path=%s from=%s presented=%s", request.url.path,
                    request.client.host if request.client else "?", "yes" if token else "no")
        return None, JSONResponse({"error": {"message": "invalid api key",
                                             "type": "invalid_request_error",
                                             "code": "invalid_api_key"}},
                                  status_code=401)

    def _require_admin(self, request: Request, *, status: int = 401) -> JSONResponse | None:
        """Admin key or a refusal; the key is rate limited per client address (issue #6).

        The limiter is consulted **before** the comparison, and that order is the
        whole point: while an address is over budget its key is not compared at
        all, so a block cannot be used to keep guessing — the guesses would be
        the thing being blocked. The cost is that a correct key is refused too
        until the window rolls, which is why the window is a minute and not an
        hour: no lockout that needs a restart, and the operator's own typo costs
        at most a minute.

        `client_address()` is the address, never a bare `X-Forwarded-For` entry:
        the header is client-written and only believed from a configured
        `proxy.trusted_proxies` peer. The comparison itself stays
        `hmac.compare_digest` (inside `KeyStore.is_admin`) — the limiter adds a
        gate in front of it, it does not replace it.

        `status` is 401 by default. The model lock (issue #21) answers 403 for the
        same condition: the operator's decision is that this state is *forbidden*
        to everyone but them, not that a credential is missing.
        """
        address = self.client_address(request)
        retry_after = self.admin_limits.retry_after(address)
        if retry_after is not None:
            self.stats.admin_key_blocks += 1
            return JSONResponse(
                {"error": {"message": f"too many failed admin attempts, retry in {retry_after} s",
                           "type": "rate_limit_error",
                           "code": "admin_rate_limited"}},
                status_code=429,
                headers={"Retry-After": str(retry_after)})
        if self.keys.is_admin(_bearer(request)):
            self.admin_limits.clear(address)
            return None
        self.stats.auth_failures += 1
        blocked = self.admin_limits.note_failure(address)
        log.warning("admin_denied path=%s from=%s", request.url.path, address or "?")
        if blocked is not None:
            # One line per *block*, not per attempt: the attempts above are
            # capped by the limiter itself (limit per window per address), and
            # the requests that follow never reach the comparison.
            log.warning("admin_blocked path=%s from=%s attempts=%d window=%.0fs retry_after=%ds",
                        request.url.path, address or "?", self.admin_limits.limit,
                        self.admin_limits.window, blocked)
        return JSONResponse({"error": {"message": "admin key required",
                                       "type": "invalid_request_error"}},
                            status_code=status)

    def _identify(self, request: Request, body: dict, model: str,
                  text: str) -> tuple[str | None, str, Any]:
        key = self.registry.key_from_headers(request.headers.items())
        if key:
            # Issue #92: the session header names the *family*, the prompt picks
            # the level inside it. A follow-up of the main conversation (ratio
            # ≈ 1.0 against the thread it opened) keeps the plain header key; a
            # spawned subagent arrives under the same header but shares almost
            # nothing with it, so it gets `<header>#<fp8>` and becomes a thread
            # of its own — one that placement may put on another host. `text` is
            # the very `prompt_text(body)` the caller passes to `register()`
            # below, so the child key names exactly the request that births it.
            key, thread = self.registry.key_for_family(key, model, text)
            # `thread` is None only when it is not born yet (the first request of
            # the session, or of a work unit): the caller's `register()` path
            # opens it. A non-None thread is already looked up and live.
            return key, "header", thread
        fp = fingerprint(model, body)
        if fp:
            t = self.registry.lookup(fp, model)
            if t is not None:
                return fp, "fingerprint", t
        match = self.registry.best_prefix_match(model, text)
        if match is not None:
            thread, _ratio = match
            self.stats.prefix_matches += 1
            return thread.key, "prefix_match", thread
        return fp, "new", None

    def _is_ephemeral(self, body: dict, prompt_tokens: int) -> bool:
        """A short single-message request holds no slot (FA-7).

        The size it is judged by is the *whole* prompt, not the user text:
        `prompt_tokens` comes from `prompt_size_text()`, so a Hermes turn with a
        101-character user message and a 300 kB system prompt is a 75 k-token
        request, not a 27-token one (issue #14). Sized from the user text, every
        agent request was ephemeral — it held no slot, never bound, never
        rebound, and the prefill bias was blind to it.
        """
        users = user_messages(body)
        if len(users) != 1:
            return False
        return prompt_tokens < self.cfg.affinity.min_prompt_tokens

    async def _forward(self, host: HostRuntime, path: str, body: dict, stream: bool,
                       request: Request) -> tuple[httpx.Response | None, str | None]:
        assert host.resolved_address is not None
        url = f"{host.resolved_address}/{path}"
        headers = {"content-type": "application/json",
                   "accept": "text/event-stream" if stream else "application/json"}
        api_key = host.cfg.api_key or _client_key(request)
        if api_key:
            headers["authorization"] = f"Bearer {api_key}"
        try:
            req = self.proxy_client.build_request("POST", url, json=body, headers=headers)
            resp = await self.proxy_client.send(req, stream=stream)
        except (httpx.HTTPError, OSError) as exc:
            return None, f"{type(exc).__name__}: {exc}"
        if resp.status_code >= 500:
            await resp.aclose()
            return None, f"HTTP {resp.status_code}"
        return resp, None

    async def _stream(self, resp: httpx.Response, host: HostRuntime,
                      model: str, *, strip_usage: bool = False,
                      thread: Any = None, ephemeral: bool = False,
                      status: int = 200) -> AsyncIterator[bytes]:
        """Pass the stream through event by event.

        Event framing (not raw chunks) is needed for two reasons: the first token
        has to be identified to separate prefill from decode, and the usage-only
        chunk that RIPPLE asked for has to be removed again before the client sees
        it. Everything else is forwarded byte for byte.
        """
        t0 = time.perf_counter()
        first_ms: float | None = None
        deltas = 0
        usage: dict[str, Any] | None = None
        buf = b""
        # Issue #18: the phase this request is in, ended where the slot ends.
        # The dispatch marked it as prefill; the first token turns it into
        # decode, and `finally` gives back whichever one is still held.
        phase = PHASE_PP
        try:
            async for chunk in resp.aiter_raw():
                buf += chunk
                while True:
                    idx = buf.find(b"\n\n")
                    if idx < 0:
                        break
                    event, buf = buf[:idx], buf[idx + 2:]
                    payload = _sse_json(event)
                    if (payload is not None and payload.get("usage")
                            and not payload.get("choices")):
                        # oMLX's usage-only chunk: we asked for it, the client
                        # did not. Record it, never forward it.
                        usage = payload["usage"]
                        if strip_usage:
                            continue
                    hits = _CONTENT_RE.findall(event)
                    deltas += len(hits)
                    if first_ms is None and hits:
                        # Time to first token: everything before it is the prefill.
                        first_ms = (time.perf_counter() - t0) * 1000.0
                        # ... and for the dashboard (issue #18): the dot stops
                        # waiting and starts showing that tokens flow.
                        if phase == PHASE_PP:
                            host.note_first_token(model)
                            phase = PHASE_TG
                    yield event + b"\n\n"
            if buf:
                yield buf
        finally:
            await resp.aclose()
            self._record_usage(host, model, usage, (time.perf_counter() - t0) * 1000.0,
                               first_token_ms=first_ms, delta_tokens=deltas,
                               status=status, thread=thread)
            # The stream owns the slot: it is released when the last byte has
            # gone out (or the client went away), not when the headers arrived.
            # Without this, `inflight` was 0 for every streaming request — the
            # normal case — so `max_inflight`, the spill threshold and the
            # (inflight+1)/weight tie-break never saw a busy node, and
            # `thread.active` was 0 while the request was still running, which
            # made a running thread an eviction candidate.
            host.end_phase(model, phase)
            host.release()
            if thread is not None:
                self.registry.leave(thread)
            elif ephemeral:
                self.registry.note_ephemeral(host.cfg.name, model)

    def _record_usage(self, host: HostRuntime, model: str,
                      usage: dict[str, Any] | None, duration_ms: float,
                      first_token_ms: float | None = None,
                      delta_tokens: int = 0, status: int = 200,
                      thread: Any = None) -> None:
        # The server's own five measurements first (issue #98): cached_tokens and
        # the two rates are read before anything below can return early, and they
        # are read for every answered request — including one that held no thread,
        # which lands on the host row and on no thread row.
        self.usage.record(host=host.cfg.name, usage=usage,
                          thread=thread.label if thread is not None else None)
        # The ledger (issue #33) next: it must see every answered request,
        # including the ones the rate logic below returns early on. `duration_ms`
        # is RIPPLE's own wall clock (dispatch to last byte) — the client's wait,
        # never presented as the node's time.
        self.host_stats.record(host.cfg.name, usage=usage,
                               client_seconds=max(0.0, duration_ms) / 1000.0,
                               ok=status < 400)
        # oMLX reports what it measured itself; use that and stop guessing.
        # One SSE delta carries ~7.5 tokens on this oMLX (measured 14.11.2026), so
        # counting deltas underestimates the rate by that factor — a last resort,
        # not the primary source.
        tokens: int | None = None
        if isinstance(usage, dict):
            exact = usage.get("generation_tokens_per_second")
            if isinstance(exact, (int, float)) and exact > 0:
                host.record_rate(model, float(exact))
                return
            value = usage.get("completion_tokens")
            if isinstance(value, int) and value > 0:
                tokens = value
            generated = usage.get("generation_duration")
            if tokens and isinstance(generated, (int, float)) and generated > 0.02:
                host.record_rate(model, tokens / float(generated))
                return
        if not isinstance(tokens, int) or tokens <= 0:
            tokens = delta_tokens
        if isinstance(tokens, int) and tokens > 0:
            # Decode rate, not wall rate: a long prompt spends most of the request
            # in the prefill and would make the host look slow (measured: 15.3
            # instead of 60.2 tok/s).
            if first_token_ms is not None:
                # Streamed: the time to the first token is the real prefill, cache
                # hit or not. No estimation needed.
                seconds = (duration_ms - first_token_ms) / 1000.0
            else:
                # Not streamed: no first-token timestamp, so price the prefill
                # with the measured rate. Conservative — a cache hit makes the
                # real prefill cheaper, which only ever underestimates the rate.
                seconds = duration_ms / 1000.0
                prompt_tokens = (usage or {}).get("prompt_tokens")
                if host.cfg.pp_tps and isinstance(prompt_tokens, int) and prompt_tokens > 0:
                    seconds -= prompt_tokens / host.cfg.pp_tps
            log.debug("usage host=%s model=%s tokens=%d dur=%.0fms ttft=%s decode=%.2fs",
                      host.cfg.name, model, tokens, duration_ms,
                      f"{first_token_ms:.0f}ms" if first_token_ms is not None else "none",
                      seconds)
            if seconds > 0.02:
                host.record_tps(model, tokens, seconds)

    def _supervise_load(self, host: HostRuntime, model: str) -> None:
        """Suspend a host's probes for the cold load this request is causing.

        No network call is needed: the placement tier already established that the
        model is not resident. `estimated_size` is what oMLX itself calculates
        with, so it is the right input for the ETA — and the ETA is what keeps the
        state from ending early and the ceiling from ending it too late.
        """
        info = host.models.get(model)
        size_bytes = info.estimated_size if info is not None else None
        size_gb = round(size_bytes / 1e9, 2) if size_bytes else None
        host.begin_loading(model, size_gb=size_gb,
                           eta_seconds=host.estimate_load_seconds(size_gb),
                           source="dispatch")
        if host.loading is not None:
            self.stats.loads_supervised += 1

    def _count_bias(self, decision) -> None:
        """Count a decision in which the prefill bias was actually in play.

        A fleet without two known `pp_tps`, a short prompt or `enabled: false`
        leaves `Decision.bias` empty and this counter untouched — which is what
        makes it useful: it says whether the term is doing anything at all.
        """
        if decision.bias:
            self.stats.prefill_bias += 1

    def _evict_slot(self, decision) -> None:
        """Drop the finished conversation that makes room for this request.

        The slot is the reservation that keeps a prefix cache warm (FA-19). A
        thread that has not been touched for a while holds that reservation for
        nothing — measured: 24 finished threads, `inflight 0`, every new
        conversation refused with 503 `no_slot`. Evicting the least recently used
        idle thread costs at most a re-prefill if it ever comes back; refusing
        costs the client its request.
        """
        spare = getattr(decision, "evict_thread", None)
        if spare is None:
            return
        self.registry.remove(spare)
        self.stats.threads_evicted += 1
        if spare.kind == "batch":
            self.stats.threads_evicted_batch += 1
        log.info("slot_evict host=%s dropped_thread=%s kind=%s idle=%.0fs",
                 spare.host, spare.label, spare.kind, time.time() - spare.last_seen)

    def _error(self, decision, model: str, t0: float, prompt_chars: int,
               thread: str | None, *, client: str | None = None,
               thread_source: str | None = None, status: int | None = None,
               prompt_tokens: int = 0,
               message: str | None = None, retry_after: int | None = None) -> JSONResponse:
        if decision is not None and decision.error_status:
            status = decision.error_status
            message = decision.error_message
        status = status or 503
        message = message or "no host available"
        reason = decision.reason if decision is not None else "error"
        if reason == "model_locked":
            # The one counter that says the lock is doing something (issue #21).
            # Counted here because every path that can refuse this way — a new
            # thread, a fallback, a retry hop — ends in `_error`.
            self.model_locked_refusals += 1
        if status == 503:
            self.stats.http_503_total += 1
        self.stats.errors_total += 1
        duration_ms = (time.perf_counter() - t0) * 1000.0
        log_request(model=model, host=None, reason=reason, prompt_chars=prompt_chars,
                    prompt_tokens=prompt_tokens,
                    duration_ms=duration_ms, status=status, thread=thread,
                    thread_source=thread_source, client=client, note=message)
        self.stats.decision(model=model, host=None, reason=reason,
                            prompt_chars=prompt_chars, prompt_tokens=prompt_tokens,
                            duration_ms=duration_ms,
                            status=status, thread=thread, thread_source=thread_source,
                            client=client, extra=message)
        return JSONResponse(
            {"error": {"message": message, "type": "ripple_error", "code": status,
                       "reason": reason}},
            status_code=status,
            headers={"retry-after": str(retry_after)} if retry_after else None)

    # -- views -------------------------------------------------------------
    def _thread_targets(self, model: str | None = None) -> dict[str, float]:
        active = 0
        per_host: dict[str, int] = {}
        for h in self.fleet.hosts:
            n = self.registry.slots_on_host(h.cfg.name)
            per_host[h.cfg.name] = n
            active += n
        out = {}
        for h in self.fleet.hosts:
            out[h.cfg.name] = round(self.cfg.target_share(h.cfg) * active, 2)
        return out

    @staticmethod
    def _model_inflight(host: HostRuntime, model: str) -> int:
        """Requests RIPPLE has in flight for `model` on `host` — nothing else.

        `host.inflight` is the node's slot count, not a per-model figure: put
        that into `models[].hosts[]` and every model row of the node carries the
        same number, whatever the traffic — a busy model and an idle one are
        indistinguishable in the `req` column. The phase bookkeeping (#18) is per
        (host, model): `begin_phase` runs right after `acquire()` and
        `end_phase` at the same release, so `pp + tg` is exactly this node's
        in-flight requests split by the model they were dispatched for.
        """
        slot = host.phases.get(model) or {}
        return int(slot.get(PHASE_PP, 0)) + int(slot.get(PHASE_TG, 0))

    def _requests_by_model(self, window_s: float | None = None) -> dict[str, dict[str, int]]:
        """Requests per (host, model) inside the served window (issue #91).

        The distribution block counts thread *slots*: a model with no warm thread
        has no share to show and used to vanish from the page while it was loaded
        on both nodes and answering requests. This is the second, honest number —
        it counts dispatches, not slots, so a model that works without a bound
        thread stays visible.

        The window is the one `/healthz` serves for the series (`window_s`,
        900 s by default), so the column and the chart below it speak about the
        same span of time. Nothing is renamed and nothing is added to
        `_node_row()`: `/admin/nodes` answers must not grow with it.
        """
        window = SERIES_WINDOW_SECONDS if window_s is None else max(1.0, float(window_s))
        since = time.time() - window
        out: dict[str, dict[str, int]] = {}
        for moment, host, model in self._request_times:
            if moment < since:
                continue
            per_host = out.setdefault(host, {})
            per_host[model] = per_host.get(model, 0) + 1
        return out

    def _thread_rows(self, limit: int = 0) -> list[dict[str, Any]]:
        """`threads.registry[]` as the page reads it, plus `active` (issue #35).

        `ThreadRegistry.snapshot()` answers "which threads hold a slot"; the
        delete control also has to know which of them has a request in flight,
        because the route refuses that one with 409 and the button must be off
        *before* the click, not after the refusal. Kept here rather than in
        `snapshot()` so `/stats → threads` keeps exactly the shape it had.
        """
        rows = self.registry.snapshot()
        active: dict[str, int] = {}
        for thread in self.registry.threads.values():
            # Two threads sharing one label cannot be told apart on the page;
            # the larger count wins, so neither looks deletable.
            active[thread.label] = max(active.get(thread.label, 0), thread.active)
        for row in rows:
            row["active"] = active.get(row["key"], 0)
            # What the server measured for this thread on the node it sits on
            # (issue #98): the last `cached_tokens` against its prompt, the
            # measured prefill and decode rate, the mean over the last eight
            # turns. `None` while nothing has been answered yet — a thread that
            # was just registered has no measurement, and 0 would say its prefix
            # was cold. `usage_history` holds the same thread's rows on the
            # nodes it left, so a move's price is one payload away.
            row["usage"] = self.usage.thread_row(row["key"], row["host"])
            row["usage_history"] = self.usage.thread_history(row["key"], row["host"])
        return rows[:limit] if limit else rows

    def _model_list_warnings(self) -> list[str]:
        """Nodes whose model list RIPPLE could not read (issue #53).

        A warning, not a state: the node is healthy and serves what is resident
        on it, but nothing new can be placed there by name. Without it the
        dashboard shows a node with 0 models and no reason — exactly the silent
        degradation the specification rules out.
        """
        # `model_list_unreadable`, not just `models_error`: a node that has not
        # been probed yet is unreadable in the same sense (placement answers 503
        # for it), and healthz must not be quieter than placement (issue #53).
        return [f"host {h.cfg.name}: model list unreadable "
                f"({h.models_error or 'never read'})"
                for h in self.fleet.hosts if h.model_list_unreadable]

    def _annotate_site(self, row: dict[str, Any], host_cfg: HostConfig) -> None:
        """Declared and derived site of one host (issue #67).

        `site` stays what the configuration claims. `site_derived` is the site the
        address RIPPLE actually uses falls into, `site_mismatch` is true when the
        two disagree and both are known. The fleet card shows that as a hint;
        `ripple doctor` turns it into a check. Placement never reads any of it —
        a site is a location, not a link and not a routing rule.
        """
        declared = self.cfg.site_of(host_cfg)
        derived = self.cfg.site_for_address(row.get("address"))
        row["site_name"] = declared.name if declared else ""
        row["site_networks"] = list(declared.networks) if declared else []
        row["site_derived"] = derived.id if derived is not None else None
        row["site_derived_name"] = derived.name if derived is not None else ""
        row["site_mismatch"] = bool(declared is not None and derived is not None
                                    and derived.id != declared.id)
        # Declared but in no network: not a contradiction, an unconfirmed claim.
        row["site_unconfirmed"] = bool(declared is not None and derived is None
                                       and row.get("address"))

    def healthz(self, window_s: float | None = None) -> dict[str, Any]:
        targets = self._thread_targets()
        active = self.registry.active_total()
        # Requests per (host, model) inside the same window the series serves
        # (issue #91) — the second number the distribution block needs.
        window = SERIES_WINDOW_SECONDS if window_s is None else max(1.0, float(window_s))
        req_window = self._requests_by_model(window)
        hosts = []
        for h in self.fleet.hosts:
            row = self._node_row(h, targets)
            row["requests_by_model"] = req_window.get(h.cfg.name, {})
            # The tachograph (issue #83): the served window only — 180 points by
            # default, never the hour the ring holds. One entry per model that
            # sampled inside it; `None` where a bucket stayed empty, so the page
            # can break the line instead of inventing a bridge.
            row["series"] = h.series(window_s)
            # The two numbers the optimizer may not guess (issue #80): the
            # measured single-stream rate and the relative load derived from it.
            # Both `null` while the ring holds no clean `n = 1` point — a fresh
            # process has no curve, and that is a state, not an error. The
            # measurement keeps its own window (900 s), so `?window=60` narrows
            # the chart without erasing the curve. Deliberately not in
            # `_node_row()`: `/admin/nodes` answers must not grow with it.
            row["capability_rate"] = h.capability_rate()
            row["relative_load"] = h.relative_load()
            # What this node measured about itself, over every request it
            # answered (issue #98) — the column in the node block reads
            # `usage.last.cached_tokens`. Deliberately not in `_node_row()`:
            # `/admin/nodes` answers must not grow with it.
            row["usage"] = self.usage.host_row(h.cfg.name)
            hosts.append(row)
        models: dict[str, dict[str, Any]] = {}
        for h in self.fleet.hosts:
            for mid, info in h.models.items():
                entry = models.setdefault(mid, {"id": mid, "hosts": []})
                entry["hosts"].append({
                    "host": h.cfg.name,
                    "available": info.available,
                    "loaded": info.loaded,
                    "pinned": info.pinned,
                    "estimated_size": info.estimated_size,
                    "actual_size": info.actual_size,
                    "context_len": info.context_len,
                    "vision": info.vision,
                    "threads": self.registry.slots(h.cfg.name, mid),
                    # In flight for *this* model on *this* node — the `req`
                    # column reads it. Not `h.inflight`: that is the node's slot
                    # count and would print the same figure on every row of the
                    # node (see `_model_inflight`).
                    "inflight": self._model_inflight(h, mid),
                    # What this node is doing with this model right now (issue
                    # #18): `pp` between dispatch and the first token, `tg`
                    # while tokens stream, None when nothing runs. The dashboard
                    # blinks the dot in that phase — from RIPPLE's own request
                    # bookkeeping, so reading /healthz costs the node nothing.
                    "phase": h.model_phase(mid),
                    "tg_tps": (h.metrics.get(mid) or {}).get("tg_tps"),
                    "allowed": h.cfg.model_allowed(mid),
                    # The operator's decision on this (host, model) pair
                    # (issue #11): None, "disabled" or "hidden" — and whether a
                    # request would actually be sent here.
                    "policy": h.policy.level(h.cfg.name, mid) if h.policy else None,
                    "dispatch": h.model_available(mid),
                    # What the availability column shows (issue #116): would this
                    # node serve `model` *right now*. `dispatch` is the wider
                    # question (it includes a cold load) and stays as it is —
                    # placement, admission and the policy view ask that one.
                    "routable": h.model_routable(mid),
                    # The lock (issue #21) protects *this* node's copy: true only
                    # where the model is locked and resident here. `models[].lock`
                    # is the model-level flag; this one is what a padlock per row
                    # in the table needs.
                    "lock": bool(h.policy is not None and h.policy.locked(mid)
                                 and info.loaded),
                    # Whose preload displaced this model on this node (issue
                    # #119), or None. The lock wins an eviction, but a model that
                    # vanished without a word is a mystery — the row says why.
                    "evicted_by": (h.displaced.get(mid) or {}).get("by"),
                })
        model_rows = []
        for mid in sorted(models):
            entry = models[mid]
            entry["hosts"].sort(key=lambda r: r["host"])
            # The lock is per model, so it is reported per model and not per host
            # (issue #21). `lock_reason` is the text while the refusal is in
            # force — i.e. while the locked model is resident somewhere, which is
            # exactly when a request can be refused for its sake. None otherwise:
            # a lock on a model that is not loaded refuses nothing.
            # Since #118 `lock` is the model's state and not "the lock protects
            # something": it is true for a cold model too, and for an oMLX builtin
            # (`builtin` below), whose lock is derived rather than stored.
            entry["lock"] = self._locked(mid)
            entry["builtin"] = self._builtin(mid)
            entry["lock_reason"] = self._lock_reason(mid)
            # The model-level availability the page paints (issue #116): routable
            # while at least one node holds it. A lock does not enter here either
            # — a locked model nobody has loaded is `locked, not resident`, and
            # `lock_reason` is None for it (the lock refuses nothing).
            entry["routable"] = any(r["routable"] for r in entry["hosts"])
            model_rows.append(entry)

        share = {}
        for h in self.fleet.hosts:
            slots = self.registry.slots_on_host(h.cfg.name)
            share[h.cfg.name] = round(slots / active, 4) if active else 0.0

        caps = self.fleet.capabilities
        return {
            "ok": True,
            "version": __version__,
            # The update hint (issue #123): `state` is newer|current|unknown|
            # disabled, and the header draws something only for `newer`. It sits
            # here and not behind its own endpoint so the page keeps reading one
            # source, and the 2 s patch keeps the hint current.
            "update": self.update_state.as_dict(),
            # `version` is the package version and never moved; the commit is what
            # answers "is the new build running?".
            "build": build_info(),
            "uptime_seconds": round(time.time() - self.stats.started_at, 1),
            # The clock the page counts down against (issue #34): the browser
            # derives `offset = server_time - Date.now()/1000` from every pull
            # and uses `now + offset` as its own clock, so a client on another
            # machine with a skewed clock still shows the right remaining time.
            "server_time": time.time(),
            "capabilities": {
                "availability": "availability" in caps,
                "residency": "residency" in caps,
                "capacity": "capacity" in caps,
                "lifecycle": "lifecycle" in caps,
                "identity": "identity" in caps,
                "prefix_cache": "prefix_cache" in caps,
                "eviction_guard": "residency" in caps and "capacity" in caps,
            },
            "warnings": (list(self.cfg.warnings) + list(self.fleet.capability_notes)
                         + self._model_list_warnings()
                         + ([f"fleet overlay {self.overlay.path}: {self.overlay.error} — "
                             f"only the config.yaml fleet is running"]
                            if self.overlay.error else [])),
            # The runtime overlay (issue #70): where it lives and what it holds.
            # `hosts[].source` says which node came from it; this says whether the
            # file could be read at all, so a node that vanished from the page has
            # a reason instead of a mystery.
            "fleet": {
                "overlay_file": str(self.overlay.path) if self.overlay.path else None,
                "overlay_persist": bool(self.overlay.persist),
                "overlay_error": self.overlay.error,
                "overlay_hosts": sorted(self.overlay.hosts),
                "overlay_overrides": {name: dict(entry)
                                      for name, entry in self.overlay.overrides.items()},
                "drain_seconds": self.cfg.fleet.drain_seconds,
            },
            # The window `hosts[].requests_by_model` counts over (issue #91): the
            # page prints it next to the column, so "12 requests" has a span and
            # not just a number. The same window the series serves.
            "requests_window_seconds": window,
            "threads": {
                "active": active,
                "target": targets,
                "actual_share": share,
                "target_share": {h.cfg.name: round(self.cfg.target_share(h.cfg), 4)
                                 for h in self.fleet.hosts},
                "registry": self._thread_rows(limit=20),
            },
            "placement": {
                "binding_strategy": self.cfg.placement.binding_strategy,
                "balance_abs_threshold": self.cfg.placement.balance_abs_threshold,
                "balance_rel_threshold": self.cfg.placement.balance_rel_threshold,
                "thread_decay_seconds": self.cfg.placement.thread_decay_seconds,
                "rebind": {
                    "enabled": self.cfg.placement.rebind.enabled,
                    "max_per_hour": self.cfg.placement.rebind.max_per_hour,
                    "safety_factor": self.cfg.placement.rebind.safety_factor,
                    "per_thread_cooldown_seconds":
                        self.cfg.placement.rebind.per_thread_cooldown_seconds,
                    "rebinds_last_hour": self.registry.rebinds_last_hour(),
                },
            },
            "hosts": hosts,
            "models": model_rows,
            # The locked models (issue #21), as a flat list: the dashboard needs
            # the set, the rows above carry the per-model flag and reason. Since
            # #118 an oMLX builtin is in it without an entry in the policy file —
            # it is locked by derivation, and `models[].builtin` says which ones.
            "locks": self._locked_models(),
            # The restart control (issue #22): whether this process may end
            # itself at all, and how much work is in flight right now. In
            # /healthz and not only behind /admin so the page can disable the
            # control *with its reason* before anyone unlocks it.
            "restart": self.restart_state(),
            # The per-host ledger (issue #33): idle/loading/prefill/decode/mixed
            # per node, the work counters behind them, and the nodes' own count
            # as a cross-check. Here rather than behind /admin because it is the
            # overview, not an action.
            "load": self.host_stats.snapshot(),
        }

    def stats_payload(self) -> dict[str, Any]:
        data = self.stats.as_dict()
        data["threads"] = self.registry.snapshot()
        # Requests refused because a locked model held the memory (issue #21).
        # Next to `threads` because both are assembled here, not in `Stats`.
        data["requests_model_locked"] = self.model_locked_refusals
        # The same ledger as `/healthz → load` (issue #33): one shape, two
        # endpoints, so the page and an operator with curl cannot disagree.
        data["host_stats"] = self.host_stats.snapshot()
        return data

    async def _merged_models(self, key: ClientKey | None = None) -> dict[str, Any]:
        # What can actually be served right now: at least one host in the pool
        # can dispatch it. A `disabled` model stays in the list only as long as
        # another host offers it (issue #11) — a model that no host would serve
        # must not be advertised, or every client that reads the list gets a
        # 503 for a model the list promised. A `hidden` model is not in this
        # set at all.
        served = {mid for h in self.fleet.healthy_hosts()
                  for mid in h.models if h.model_available(mid)}
        seen: dict[str, dict[str, Any]] = {}
        for h in self.fleet.healthy_hosts():
            for mid, info in h.models.items():
                if not h.cfg.model_allowed(mid):
                    continue
                if h.policy is not None and h.policy.hides(h.cfg.name, mid):
                    # `hidden` (issue #11) removes the model from this host's
                    # contribution, whether or not another host still serves it.
                    continue
                if mid not in served:
                    continue
                if key is not None and not key.model_allowed(mid):
                    continue        # a key sees only what it may call
                row = seen.setdefault(mid, {
                    "id": mid, "object": "model", "owned_by": "ripple",
                    "created": 0,
                })
                if info.context_len:
                    row["max_model_len"] = max(row.get("max_model_len", 0),
                                               info.context_len)
        if not seen and key is None and not any(h.models for h in self.fleet.healthy_hosts()):
            # Fallback only without a key and only when the fleet knows nothing:
            # the entry host's own list would leak models the key is not allowed
            # to see, and when the hosts *do* know their models an empty result
            # is the honest answer (everything is filtered out by the allow-list
            # or by the operator's policy) — not a reason to ask oMLX directly.
            entry = self.fleet.entry_host()
            if entry is not None and entry.resolved_address:
                try:
                    r = await self.proxy_client.get(entry.resolved_address + "/v1/models",
                                                    headers={"authorization":
                                                             f"Bearer {entry.cfg.api_key}"}
                                                    if entry.cfg.api_key else {})
                    payload = r.json()
                    # The raw list is oMLX's, not RIPPLE's: a model the operator
                    # hid here must not slip through the fallback path.
                    if isinstance(payload, dict) and isinstance(payload.get("data"), list):
                        payload["data"] = [
                            m for m in payload["data"]
                            if not (entry.policy is not None
                                    and entry.policy.hides(entry.cfg.name,
                                                           str(m.get("id"))))]
                    return payload
                except (httpx.HTTPError, ValueError):
                    pass
        return {"object": "list", "data": [seen[k] for k in sorted(seen)]}
